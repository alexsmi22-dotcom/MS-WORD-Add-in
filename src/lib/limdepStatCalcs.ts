type Read = (key: string) => string;
type Align = ("left" | "right")[];
const refuse = (text: string): StatOutput => ({ text, ok: false });
const q = (s: string): string => `“${s}”`;

// ---------------------------------------------------------------------------------------------------- formatting

const D = 4;
const ALIGN6: Align = ["left", "right", "right", "right", "right", "right"];
const COEF_HEAD = ["Term", "Coefficient", "SE", "z", "p", "95% CI"];

/** "a to b" (the word, never a dash that could read as a minus). */
function ci(lo: number, hi: number, d = D): string {
  return `${fmtFixed(lo, d)} to ${fmtFixed(hi, d)}`;
}
function termRow(t: ModelTerm, label = t.name): string[] {
  return [label, fmtFixed(t.coef, D), fmtFixed(t.se, D), fmtFixed(t.stat, 2), fmtP(t.p), ci(t.ciLo, t.ciHi)];
}
function pText(p: number): string {
  return p < 0.001 ? `p ${P_BELOW}` : `p = ${p.toFixed(3)}`;
}
function list(names: string[]): string {
  return names.length ? names.join(", ") : "a constant";
}
/** The model statistics as one sentence: N, ℓ, LR χ² with its p, pseudo R², AIC, BIC. */
function statsLine(m: LimdepModel): string {
  const parts: string[] = [];
  let pLR: number | undefined;
  for (const s of m.stats) if (s.label === "Prob > χ²") pLR = s.value;
  for (const s of m.stats) {
    if (s.label === "Prob > χ²" || s.label.startsWith("/") || s.label === "N") continue;
    if (s.label.startsWith("LR χ²") || s.label.startsWith("Wald χ²")) parts.push(`${s.label} = ${fmtFixed(s.value, 3)}${pLR !== undefined ? `, ${pText(pLR)}` : ""}`);
    else if (s.label === "Pseudo R²") parts.push(`McFadden pseudo R² = ${fmtFixed(s.value, 4)}`);
    else if (s.label === "Selected") continue;
    else parts.push(`${s.label} = ${fmtFixed(s.value, 3)}`);
  }
  return `${parts.join("; ")}.`;
}

// ---------------------------------------------------------------------------------------------------- reading

interface Cols {
  y: number[];
  X: number[][];
  names: string[];
  depName: string;
  rowNumbers: number[];
  notes: string[];
}

function readTable(read: Read, specKey = "spec"): { data: RegDataset; spec: RegSpec } | { error: string } {
  const parsed = parseRegData(read("data"));
  if (!parsed.ok) return { error: parsed.reason };
  const spec = parseSpec(read(specKey));
  if ("error" in spec) return { error: spec.error };
  return { data: parsed.data, spec };
}

function toCols(data: RegDataset, spec: RegSpec): Cols | { error: string } {
  const sel = selectColumns(data, spec, {});
  if (!sel.ok) return { error: sel.reason };
  const c = sel.cols;
  const y = Array.from(c.y);
  return { y, X: y.map((_, i) => c.X.map((col) => col[i])), names: c.names, depName: c.depName, rowNumbers: c.rowNumbers, notes: c.notes };
}

function readerNotes(data: RegDataset, notes: string[]): string[] {
  const out = [...notes];
  if (!data.named) out.unshift("The table had no header row, so its columns are named y, x1, x2… in order.");
  out.push("Rows with an empty or NA cell in a column the model uses are dropped (listwise deletion).");
  return out;
}

/** A blank field is "no value"; anything else must be a number (readFinanceField: true minus, decimal comma, grouping). */
function optionalNumber(raw: string, label: string): number | null | { error: string } {
  if (!(raw ?? "").trim()) return null;
  const v = readFinanceField(raw);
  if (!Number.isFinite(v)) return { error: `${label}: ${q(raw.trim())} is not a number (leave it blank for none).` };
  return v;
}

function fail(e: unknown, what: string): StatOutput {
  if (e instanceof LimdepRefusal) return refuse(e.message);
  return refuse(`The ${what} could not be computed for these data (${(e as Error).message}). Check the columns for extreme values.`);
}

