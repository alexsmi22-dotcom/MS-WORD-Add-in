import { RANDOM_VIBRATION_CALCS } from "../randomVibrationCalcs";
import { KALMAN_CALCS } from "../kalmanCalcs";
const all = [...RANDOM_VIBRATION_CALCS, ...KALMAN_CALCS] as any[];
const run = (id: string, over: Record<string, string> = {}) => {
  const c = all.find((x) => x.id === id);
  const vals: Record<string, string> = Object.fromEntries(c.fields.map((f: any) => [f.key, f.default]));
  Object.assign(vals, over);
  return c.compute((k: string) => vals[k] ?? "");
};
const show = (tag: string, o: any) => console.log(tag, o.ok === false ? "REFUSED " + o.text : JSON.stringify((o.outputs ?? []).map((x: any) => [x.key, x.value, x.unit])));
test("x", () => {
  for (const [fn, q] of [["100", "10"], ["30", "500"], ["1990", "50"], ["21", "1.6666666667"]]) show("rv " + fn, run("vib-random-psd", { fn, damp: q }));
  show("rv kHz", run("vib-random-psd", { fn: "0.1 kHz" }));
  show("rv blankfn", run("vib-random-psd", { fn: "" }));
  show("rv rpm", run("vib-random-psd", { fn: "6000 rpm" }));
  show("base", run("vib-base-excitation"));
  show("base disp", run("vib-base-excitation", { ikind: "disp", amp: "1 mm" }));
  show("base acc in", run("vib-base-excitation", { ikind: "disp", amp: "0.04 in" }));
  show("shaft", run("vib-shaft-critical"));
  show("shaft nomass", run("vib-shaft-critical", { masses: "" }));
  show("shaft 2m", run("vib-shaft-critical", { masses: "20 0.3\n10 0.7", rho: "" }));
  show("shaft lb in", run("vib-shaft-critical", { masses: "44.0925 19.685", munit: "lb", xunit: "in", rho: "" }));
  show("kal cv", run("kalman-steady"));
  show("kal rw", run("kalman-steady", { model: "rw" }));
  show("kal mat3", run("kalman-steady", { model: "matrix", F: "1 0.1 0.005\n0 1 0.1\n0 0 1", H: "1 0 0\n0 0 1", Q: "0.001 0 0\n0 0.01 0\n0 0 0.1", R: "0.25 0.01\n0.01 0.04" }));
  show("kal undetect", run("kalman-steady", { model: "matrix", F: "1 0\n0 1.1", H: "1 0", Q: "1 0\n0 1", R: "1" }));
  show("kal stable unobs", run("kalman-steady", { model: "matrix", F: "1 0\n0 0.5", H: "1 0", Q: "1 0\n0 1", R: "1" }));
  show("kal marginal", run("kalman-steady", { model: "matrix", F: "1 0\n0 1", H: "1 0", Q: "1 0\n0 1", R: "1" }));
  show("kal hugeQ", run("kalman-steady", { model: "matrix", F: "1 1\n0 1", H: "1 0", Q: "1e30 0\n0 1e30", R: "1e-30" }));
  const a = (o: any) => show("att " + JSON.stringify(o), run("attitude-convert", o));
  a({});
  a({ frame: "extrinsic" });
  a({ seqA: "ZXZ", a1: "45", a2: "30", a3: "60" });
  a({ seqA: "XYZ", frame: "extrinsic", a1: "0.5 rad", a2: "-40", a3: "170" });
  a({ seqA: "ZYX", a1: "30", a2: "90", a3: "10" });
  a({ formA: "quat", quatA: "1, 2, 3, 4" });
  a({ formA: "quat", order: "first", quatA: "4, 1, 2, 3" });
  a({ formA: "dcm", dcmA: "0 -1 0\n1 0 0\n0 0 1" });
  a({ formA: "axis", axisA: "1, 1, 1", angleA: "120" });
  a({ op: "compose" });
  a({ op: "slerp", t: "0.3" });
});
