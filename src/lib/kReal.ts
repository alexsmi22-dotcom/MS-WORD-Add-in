// Real K-theory KO — SCOPE-NUMERICS-TOPOLOGY §B2.
//
// WHAT IS COMPUTED, AND WHY IT IS A COMPUTATION. Real Bott periodicity says
// KO^{-q}(pt) depends only on q mod 8:
//
//     q mod 8 :  0   1    2    3  4  5  6  7
//     KO^{-q} :  ℤ  ℤ/2  ℤ/2  0  ℤ  0  0  0
//
// and the suspension isomorphism gives the reduced groups of every sphere from
// that one row: K̃O^{-q}(Sⁿ) = KO^{-(q+n)}(pt). That is a theorem doing the
// work, so there is no cap on n beyond a display limit.
//
// WHAT IS CITED, NEVER COMPUTED PAST THE THEOREM. K̃O⁰(ℝPⁿ) is cyclic of order
// 2^φ(n), φ(n) = #{s : 0 < s ≤ n, s ≡ 0, 1, 2, 4 (mod 8)}, generated by L − 1
// (Adams, Ann. Math. 75 (1962) 603–632, Thm 7.4). The SECOND ROUTE below is an
// independent count: the nonzero Atiyah–Hirzebruch E₂ entries
// H̃^q(ℝPⁿ; KO^{-q}(pt)), each computed from the cellular cochain complex of
// ℝPⁿ (coboundaries alternately 0 and ×2). The two must agree or the answer is
// refused.
//
// REFUSED BY NAME: graded KO^{-q}(ℝPⁿ) for q ≠ 0, KO of ℂPⁿ (Sanderson 1964 —
// not built), and every product (KO Künneth has Tor terms).

import type { KTheoryResult } from "./alexander";

// ---------------------------------------------------------------------------
// Shared text normalisation — every space the tool DISPLAYS must parse back,
// so superscripts, ×, ℝ/ℂ/ℍ and the Unicode minus are folded here.
// ---------------------------------------------------------------------------

const SUP: Record<string, string> = {
  "⁰": "0", "¹": "1", "²": "2", "³": "3", "⁴": "4", "⁵": "5", "⁶": "6", "⁷": "7", "⁸": "8", "⁹": "9", "⁻": "-",
};
const SUB: Record<string, string> = {
  "₀": "0", "₁": "1", "₂": "2", "₃": "3", "₄": "4", "₅": "5", "₆": "6", "₇": "7", "₈": "8", "₉": "9",
};

/** Lower-cases and folds the Unicode spellings the outputs themselves use. */
export function normaliseTopologyText(raw: string): string {
  // "K̃O" carries a combining tilde between the letters; move it out of the word.
  let s = raw.replace(/([Kk])̃([Oo]?)/g, "~$1$2");
  // Ω₅ˢᴼ (the displayed group name) and 𝔑₅ (unoriented) read back as omega.
  s = s.replace(/ˢᴼ/g, "^so").replace(/𝔑/g, " unoriented omega");
  s = s.replace(/[⁰¹²³⁴⁵⁶⁷⁸⁹⁻]+/g, (run) => "^" + Array.from(run).map((c) => SUP[c]).join(""));
  s = s.replace(/[₀₁₂₃₄₅₆₇₈₉]+/g, (run) => "_" + Array.from(run).map((c) => SUB[c]).join(""));
  s = s
    .replace(/̃/g, "~")
    .replace(/[−–]/g, "-")
    .replace(/[×⨯]/g, " x ")
    .replace(/[⊔∐]/g, " + ")
    .replace(/ℝ/g, "r").replace(/ℂ/g, "c").replace(/ℍ/g, "h").replace(/ℤ/g, "z")
    .replace(/[Ωω]/g, "omega")
    .toLowerCase();
  // "s^1xs^1" — a product sign glued between a digit and the next name.
  s = s.replace(/(\d)x([a-z(])/g, "$1 x $2");
  return s.replace(/\s+/g, " ").trim();
}

/** Unicode superscript of an integer, for display ("S¹⁰"). */
export function sup(n: number | string): string {
  const inv: Record<string, string> = {};
  for (const [k, v] of Object.entries(SUP)) inv[v] = k;
  return Array.from(String(n)).map((c) => inv[c] ?? c).join("");
}

/** Unicode subscript of an integer ("Ω₅"). */
export function sub(n: number | string): string {
  const inv: Record<string, string> = {};
  for (const [k, v] of Object.entries(SUB)) inv[v] = k;
  return Array.from(String(n)).map((c) => inv[c] ?? c).join("");
}

/**
 * Typesets an abelian group written in the engines' ASCII ("Z^2", "Z + Z/2",
 * "Z/2^5") as ℤ², ℤ ⊕ ℤ/2, ℤ/2⁵. Already-typeset text passes through.
 */
export function typesetGroup(g: string): string {
  return g
    .replace(/\bZ\b/g, "ℤ")
    .replace(/\s\+\s/g, " ⊕ ")
    .replace(/\^\(?(\d+)\)?/g, (_m, d: string) => sup(d));
}

/** A finitely generated abelian group in canonical form: free rank + torsion orders. */
export interface GroupShape { free: bigint; torsion: bigint[] }

/**
 * Reads a group back from its display — "ℤ²", "ℤ ⊕ ℤ/2", "ℤ/2⁵", "0", and the
 * ASCII spellings "Z^2", "Z + Z/2". Null when the text is not a group. This is
 * the reader half of the display contract: print → read → the same group.
 */
export function parseGroup(text: string): GroupShape | null {
  let s = text.replace(/[⁰¹²³⁴⁵⁶⁷⁸⁹]+/g, (run) => "^" + Array.from(run).map((c) => SUP[c]).join(""));
  s = s.replace(/ℤ/g, "Z").replace(/⊕/g, "+").replace(/\s+/g, "").trim();
  if (s === "0") return { free: 0n, torsion: [] };
  let free = 0n;
  const torsion: bigint[] = [];
  for (const part of s.split("+")) {
    let m: RegExpExecArray | null;
    if ((m = /^\(?Z\/(\d{1,7})(?:\^(\d{1,7}))?\)?(?:\^(\d{1,4}))?$/.exec(part))) {
      // Z/m, Z/2^k (order 2^k), (Z/2)^r (r copies)
      const order = m[2] ? BigInt(m[1]) ** BigInt(m[2]) : BigInt(m[1]);
      const copies = m[3] ? parseInt(m[3], 10) : 1;
      if (/^\(/.test(part) && !m[3] && m[2]) return null;
      for (let i = 0; i < copies; i++) torsion.push(order);
    } else if ((m = /^Z(?:\^(\d{1,20}))?$/.exec(part))) {
      free += m[1] ? BigInt(m[1]) : 1n;
    } else if (part === "0") {
      continue;
    } else {
      return null;
    }
  }
  torsion.sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
  return { free, torsion };
}

/** Largest index read from text. §D pins S^1000001, so the limit sits above it. */
export const MAX_SPACE_INDEX = 999_999_999;

export type SpaceFactor =
  | { kind: "point" }
  | { kind: "sphere"; n: number }
  | { kind: "rp"; n: number }
  | { kind: "cp"; n: number }
  | { kind: "hp"; n: number }
  | { kind: "torus"; n: number };

/** Strips the framing words people type around a space name. */
export function stripSpaceFiller(s: string): string {
  return s
    .replace(/\b(compute|calculate|find|give|show|what|is|are|the|of|for|a|an|please|space|group|groups)\b/g, " ")
    .replace(/[()?]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

const idx = (d: string | undefined): number | null => {
  if (d == null || d.length === 0 || d.length > 9) return null;
  const n = parseInt(d, 10);
  return Number.isFinite(n) && n >= 0 && n <= MAX_SPACE_INDEX ? n : null;
};

/**
 * One factor, read from an ALREADY normalised and filler-stripped string. The
 * whole string must be the factor (anchored) — an unanchored match is how a
 * product used to be answered by its first factor.
 */
export function parseSpaceFactor(text: string): SpaceFactor | null | "too-large" {
  const s = text.replace(/\s+/g, " ").trim();
  if (/^(point|pt|one point)$/.test(s)) return { kind: "point" };
  let m: RegExpExecArray | null;
  const big = (d: string) => d.length > 9 || parseInt(d, 10) > MAX_SPACE_INDEX;
  if ((m = /^(?:s|sphere)\s*\^?\s*\{?(\d+)\}?$/.exec(s)) || (m = /^(\d+)-?sphere$/.exec(s))) {
    if (big(m[1])) return "too-large";
    const n = idx(m[1]);
    return n === null ? null : { kind: "sphere", n };
  }
  if (s === "sphere") return { kind: "sphere", n: 2 };
  if (s === "circle") return { kind: "sphere", n: 1 };
  if (/^(real )?projective plane$/.test(s)) return { kind: "rp", n: 2 };
  if (s === "complex projective plane") return { kind: "cp", n: 2 };
  if ((m = /^(?:rp|real projective)\s*\^?\s*\{?(\d+)\}?$/.exec(s))) {
    if (big(m[1])) return "too-large";
    const n = idx(m[1]);
    return n === null ? null : { kind: "rp", n };
  }
  if ((m = /^(?:cp|complex projective)\s*\^?\s*\{?(\d+)\}?$/.exec(s))) {
    if (big(m[1])) return "too-large";
    const n = idx(m[1]);
    return n === null ? null : { kind: "cp", n };
  }
  if ((m = /^(?:hp|quaternionic projective)\s*\^?\s*\{?(\d+)\}?$/.exec(s))) {
    if (big(m[1])) return "too-large";
    const n = idx(m[1]);
    return n === null ? null : { kind: "hp", n };
  }
  if (s === "torus") return { kind: "torus", n: 2 };
  if ((m = /^(?:t|torus)\s*\^?\s*\{?(\d+)\}?$/.exec(s)) || (m = /^(\d+)-?torus$/.exec(s))) {
    if (big(m[1])) return "too-large";
    const n = idx(m[1]);
    return n === null || n < 1 ? null : { kind: "torus", n };
  }
  return null;
}

/** Splits a product "A x B x C" (also "*"). Returns one entry for a non-product. */
export function splitProduct(s: string): string[] {
  return s.split(/\s+x\s+|\s*\*\s*/).map((t) => t.trim()).filter((t) => t.length > 0);
}

/** Display name of a factor, in the notation the parser reads back. */
export function factorName(f: SpaceFactor): string {
  switch (f.kind) {
    case "point": return "a point";
    case "sphere": return `S${sup(f.n)}`;
    case "rp": return `ℝP${sup(f.n)}`;
    case "cp": return `ℂP${sup(f.n)}`;
    case "hp": return `ℍP${sup(f.n)}`;
    case "torus": return `T${sup(f.n)}`;
  }
}

