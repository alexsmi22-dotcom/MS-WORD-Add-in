export interface KOResult extends KTheoryResult {
  theory: "KO";
  /** Set when the request was understood but is refused by name. */
  refused?: string;
  /** Extra display lines (the graded row for a point, for instance). */
  graded?: string[];
  /** The answer lines, ready to show (the refusal itself when refused). */
  display: string[];
  /** The degree asked for (KO^degree); 0 when none was given. */
  degree: number;
}

/**
 * Homotopy groups of the K-theory SPECTRA — π_n(KO) = KO⁻ⁿ(pt), π_n(KU) = ℤ for
 * n even and 0 for n odd, π_n(KSp) = π_{n+4}(KO) (Bott 1959). "pi_3(KO)" is
 * NOT the sphere's stable stem π₃ˢ = ℤ/24 — answering it from the stem table
 * was a live wrong answer. Also reads KO_n(pt) (= π_n(KO)) and "homotopy
 * groups of KO". Null when no spectrum is named.
 */
export function spectrumHomotopy(query: string): { title: string; display: string[]; steps: string[]; caveats: string[] } | null {
  const s = normaliseTopologyText(query).split("=")[0];
  // (?![a-z]) not \b: in "ko_3(pt)" the underscore is a word character.
  const spec = /\b(ksp|ko|ku|bu|bo)(?![a-z])|\bk[- ]?theory\b|\bcomplex k[- ]?theory\b/.exec(s);
  if (!spec) return null;
  const which: "KO" | "KU" | "KSp" =
    spec[1] === "ksp" ? "KSp" : spec[1] === "ko" || spec[1] === "bo" ? "KO" : "KU";
  const idx = /(?:\bpi|π)\s*_?\s*\{?\s*(\d{1,6})\s*\}?/.exec(s) ?? /\bk(?:o|u|sp)\s*_\s*\{?\s*(\d{1,6})\s*\}?\s*\(\s*(?:pt|point)\s*\)/.exec(s);
  const row = /\bhomotopy groups?\b|\bstable homotopy\b|\bcoefficients?\b/.test(s);
  if (!idx && !row) return null;
  const val = (n: number): string =>
    which === "KO" ? koOfPoint(n) : which === "KSp" ? koOfPoint(n + 4) : n % 2 === 0 ? "ℤ" : "0";
  const period = which === "KU" ? 2 : 8;
  const ns = idx ? [parseInt(idx[1], 10)] : Array.from({ length: period }, (_, i) => i);
  return {
    title: `Homotopy of the ${which} spectrum`,
    display: ns.map((n) => `π${sub(n)}(${which}) = ${val(n)}`),
    steps: [
      which === "KU"
        ? "Complex Bott periodicity: π_n(KU) = K⁻ⁿ(pt) is ℤ for n even and 0 for n odd."
        : which === "KO"
          ? "Real Bott periodicity: π_n(KO) = KO⁻ⁿ(pt) = ℤ, ℤ/2, ℤ/2, 0, ℤ, 0, 0, 0 for n ≡ 0…7 (mod 8)."
          : "Symplectic K-theory is real K-theory shifted by 4: π_n(KSp) = π_{n+4}(KO).",
      "These are the homotopy groups of the K-theory SPECTRUM — not the stable stems of the sphere (π₃ˢ = ℤ/24, while π₃(KO) = 0).",
    ].map((x) => x.replace(/π_n/g, "πₙ").replace(/π_\{n\+4\}/g, "πₙ₊₄")),
    caveats: [BOTT_CITE],
  };
}

/** True when the text asks for REAL K-theory. */
export function isKoQuery(text: string): boolean {
  const s = normaliseTopologyText(text);
  return /\breal k[- ]?theory\b|\bko[- ]?theory\b|\bko\b|\bko\s*[\^(_~]/.test(s);
}

const refuse = (space: string, reason: string, steps: string[] = [], caveats: string[] = []): KOResult => ({
  theory: "KO", space, k0: "—", k1: "—", reducedK0: "—", refused: reason, steps, caveats,
  display: [reason], degree: 0,
});

const BOTT_CITE =
  "Real Bott periodicity: KO⁻ᵏ(pt) = ℤ, ℤ/2, ℤ/2, 0, ℤ, 0, 0, 0 for k ≡ 0…7 (mod 8) (Bott 1959; Atiyah, K-Theory, 1967).";
const CONVENTION =
  "Convention: K̃O⁻ᵏ(Sⁿ) = KO⁻⁽ᵏ⁺ⁿ⁾(pt) (suspension isomorphism); KO⁰(X) = ℤ ⊕ K̃O⁰(X) for connected X.";

/**
 * KO of the spaces where Bott periodicity or a published closed form settles
 * the answer. Takes the whole query ("KO of S^1", "KO^1(RP^3)", "real k-theory
 * of a point"). Null only when no space could be read at all; a space that was
 * read but is outside scope is a REFUSAL BY NAME (`refused`), never null.
 */
export function koTheory(query: string): KOResult | null {
  // A displayed answer line ("K̃O⁰(S¹) = ℤ/2") reads back by its left side.
  let s = normaliseTopologyText(query).split("=")[0];
  // The degree, if given: KO^1, KO^-2, KO^{-2}, KO^0. "KO" alone means degree 0.
  let degree = 0;
  const deg = /\bko\s*\^\s*\{?\s*(-?\d{1,6})\s*\}?/.exec(s);
  if (deg) degree = parseInt(deg[1], 10);
  s = s
    .replace(/\breal k[- ]?theory\b/g, " ")
    .replace(/\bko[- ]?theory\b/g, " ")
    .replace(/~?\bko\b\s*(\^\s*\{?\s*-?\d{1,6}\s*\}?)?~?/g, " ")
    .replace(/\b(reduced|real)\b|~/g, " ")
    // "… via the Atiyah–Hirzebruch spectral sequence": the method named is not
    // part of the space (the answer says which route it used).
    .replace(/\b(via|using|by|from|with)\b.*$/, " ");
  s = stripSpaceFiller(s);
  if (!s) return null;

  const parts = splitProduct(s);
  if (parts.length > 1) {
    const fs = parts.map((p) => parseSpaceFactor(p));
    const names = parts.map((p, i) => {
      const f = fs[i];
      return f && f !== "too-large" ? factorName(f) : p;
    });
    // A product of points and S⁰'s is a finite set of points: no Tor term.
    const discrete = fs.every((f) => f && f !== "too-large" && (f.kind === "point" || (f.kind === "sphere" && f.n === 0)));
    if (discrete && fs.length <= 20) {
      const count = 2 ** fs.filter((f) => (f as SpaceFactor).kind === "sphere").length;
      const name = names.join(" × ");
      const g = (d: number, c: number) => (koOfPoint(-d) === "0" || c === 0 ? "0" : c === 1 ? koOfPoint(-d) : koOfPoint(-d) === "ℤ" ? `ℤ${sup(c)}` : `(${koOfPoint(-d)})${sup(c)}`);
      return {
        theory: "KO", space: name, degree,
        k0: g(degree, count), k1: g(1, count), reducedK0: g(degree, count - 1),
        display: [`K̃O${sup(degree)}(${name}) = ${g(degree, count - 1)}`, `KO${sup(degree)}(${name}) = ${g(degree, count)}`],
        steps: [
          `${name} is a set of ${count} points (S⁰ is two points), so KO${sup(degree)} is the sum of ${count} copies of KO${sup(degree)}(pt) = ${koOfPoint(-degree)}: there is no Tor term for a discrete space.`,
        ],
        caveats: [BOTT_CITE],
      };
    }
    return refuse(
      names.join(" × "),
      `KO of a product (${names.join(" × ")}) is not computed: the KO Künneth formula has Tor terms, so the answer is not the tensor product of the factors. A product is never reduced to one of its factors.`,
      [],
      ["Complex K-theory of a product of spheres IS computed (Künneth is exact there, everything being torsion-free) — ask \"k-theory of S¹ × S¹\"."],
    );
  }

  const f = parseSpaceFactor(s);
  if (f === "too-large") {
    return refuse(s, `The index is above the display limit (${MAX_SPACE_INDEX.toLocaleString("en-US")}). The answer depends only on n mod 8, so reduce n mod 8 and ask again.`);
  }
  if (!f) return null;

  // Identifications that put a space in Bott's reach: T¹ = S¹, ℂP¹ ≅ S², ℍP¹ ≅ S⁴.
  const SPHERE_ALIAS: Record<string, [number, string]> = {
    torus: [1, "T¹ is the circle S¹"],
    cp: [2, "ℂP¹ is diffeomorphic to S² (the Riemann sphere)"],
    hp: [4, "ℍP¹ is diffeomorphic to S⁴"],
  };
  const alias = f.kind !== "point" && f.kind !== "sphere" && f.kind !== "rp" && f.n === 1 ? SPHERE_ALIAS[f.kind] : undefined;

  if (f.kind === "torus" && !alias) {
    return refuse(factorName(f), `The torus T${sup(f.n)} is a product of circles, and KO of a product is not computed: the KO Künneth formula has Tor terms.`);
  }
  if (f.kind === "cp" && !alias) {
    return refuse(
      factorName(f),
      `KO of ℂP${sup(f.n)} is not built in this release. The published computation is Sanderson (Proc. London Math. Soc., 1964); it is cited here, not reproduced.`,
    );
  }
  if (f.kind === "hp" && !alias) {
    return refuse(factorName(f), `KO of ℍP${sup(f.n)} is not computed here.`);
  }

  // A point, or ℝP⁰ (which IS a point — said so).
  if (f.kind === "point" || (f.kind === "rp" && f.n === 0)) {
    const graded = Array.from({ length: 8 }, (_, q) => `KO${sup(-q === 0 ? 0 : -q)}(pt) = ${koOfPoint(q)}`);
    // No parenthetical gloss: the name must read back (a step says ℝP⁰ is a point).
    const name = f.kind === "rp" ? "ℝP⁰" : "a point";
    return {
      theory: "KO",
      space: name,
      k0: koOfPoint(-degree),
      k1: koOfPoint(-1),
      reducedK0: "0",
      graded,
      degree,
      display: degree === 0 ? graded : [`KO${sup(degree)}(pt) = ${koOfPoint(-degree)}`, ...graded],
      steps: [
        ...(f.kind === "rp" ? ["ℝP⁰ is a single point, so this is KO of a point."] : []),
        `KO${sup(degree)}(pt) = ${koOfPoint(-degree)}: the real Bott row read at k = ${-degree} ≡ ${(((-degree) % 8) + 8) % 8} (mod 8).`,
        "The whole row, q = 0…7: " + KO_POINT.join(", ") + ".",
      ],
      caveats: [BOTT_CITE, "KO⁰(pt) = ℤ counts real vector spaces by dimension; the ℤ/2 in degrees −1 and −2 is what distinguishes KO from complex K."],
    };
  }

  if (f.kind === "sphere" || alias) {
    const n = alias ? alias[0] : (f as { n: number }).n;
    const name = factorName(f);
    const aliasStep = alias ? [`${alias[1]}, so Bott periodicity settles it as for S${sup(n)}.`] : [];
    const red = (d: number) => koOfPoint(n - d); // K̃O^{d}(Sⁿ) = KO^{d-n}(pt) = KO^{-(n-d)}(pt)
    const full = (d: number) => (n === 0 ? directSum(koOfPoint(-d), koOfPoint(-d)) : directSum(koOfPoint(-d), red(d)));
    const r = (((n - degree) % 8) + 8) % 8;
    return {
      theory: "KO",
      space: name,
      k0: full(degree),
      k1: full(1),
      reducedK0: red(degree),
      degree,
      display: [`K̃O${sup(degree)}(${name}) = ${red(degree)}`, `KO${sup(degree)}(${name}) = ${full(degree)}`],
      steps: [
        ...aliasStep,
        `K̃O${sup(degree)}(${name}) = KO${sup(degree - n)}(pt) by the suspension isomorphism.`,
        `${n - degree} ≡ ${r} (mod 8), and the real Bott row at ${r} is ${KO_POINT[r]}.`,
        n === 0 && !alias
          ? `S⁰ is two points, so KO${sup(degree)}(S⁰) = KO${sup(degree)}(pt) ⊕ KO${sup(degree)}(pt) = ${full(degree)}.`
          : `Adding back the point summand: KO${sup(degree)}(${name}) = KO${sup(degree)}(pt) ⊕ K̃O${sup(degree)}(${name}) = ${full(degree)}.`,
      ],
      caveats: [
        BOTT_CITE,
        CONVENTION,
        "This is REAL K-theory, 8-periodic. Complex K-theory is 2-periodic and gives a different answer (for S¹, K̃⁰ = 0 while K̃O⁰ = ℤ/2).",
      ],
    };
  }

  // ℝPⁿ, n ≥ 1: degree 0 only, cited (Adams), cross-checked by the AHSS count.
  const n = f.n;
  const name = factorName(f);
  if (degree !== 0) {
    return refuse(
      name,
      `KO${sup(degree)} of ℝP${sup(n)} (degree ${degree} ≠ 0) needs the full Atiyah–Hirzebruch computation; only K̃O⁰ is a published closed form (Adams 1962).`,
    );
  }
  const phi = adamsPhi(n);
  const entries = n <= 100_000 ? ahssKoEntriesRP(n) : null;
  if (entries && (entries.length !== phi || entries.some((e) => e.group !== "ℤ/2"))) {
    return refuse(name, `Internal disagreement: Adams' φ(${n}) = ${phi} but the Atiyah–Hirzebruch E₂ count is ${entries.length}. Refused rather than reporting either.`);
  }
  const red = cyclic2(phi);
  return {
    theory: "KO",
    space: name,
    k0: directSum("ℤ", red),
    k1: "not computed (only K̃O⁰ of ℝPⁿ is a published closed form)",
    reducedK0: red,
    degree: 0,
    display: [`K̃O⁰(${name}) = ${red}`, `KO⁰(${name}) = ${directSum("ℤ", red)}`],
    steps: [
      `φ(${n}) = #{s : 0 < s ≤ ${n}, s ≡ 0, 1, 2, 4 (mod 8)} = ${phi}.`,
      `K̃O⁰(ℝP${sup(n)}) is cyclic of order 2ᵠ⁽${sup(n)}⁾ = 2${sup(phi)}, generated by L − 1 (L the canonical line bundle): ${red}.`,
      entries
        ? `Second route: the nonzero Atiyah–Hirzebruch E₂ entries H̃ᵏ(ℝP${sup(n)}; KO⁻ᵏ(pt)), from the cellular cochain complex of ℝP${sup(n)}, sit at k = ${entries.length <= 24 ? entries.map((e) => e.q).join(", ") : `${entries.slice(0, 12).map((e) => e.q).join(", ")}, …`} — ${entries.length} entries, each ℤ/2, agreeing with φ(${n}) = ${phi}.`
        : `The Atiyah–Hirzebruch cross-check is skipped above n = 100 000; the closed form is the theorem.`,
      `KO⁰(ℝP${sup(n)}) = ℤ ⊕ K̃O⁰ = ${directSum("ℤ", red)}.`,
    ],
    caveats: [
      "K̃O⁰(ℝPⁿ) = ℤ/2ᵠ⁽ⁿ⁾: Adams, \"Vector fields on spheres\", Ann. of Math. 75 (1962) 603–632, Theorem 7.4. CITED, not derived: the E₂ count matches the order only because Adams proved every entry survives with no extension ambiguity.",
      ...(n === 1 ? ["ℝP¹ is the circle S¹, and K̃O⁰(S¹) = ℤ/2 from Bott periodicity agrees — a consistency check between the two routes."] : []),
      "Only degree 0 is given for ℝPⁿ; KO⁻ᵏ(ℝPⁿ) for k ≠ 0 is refused by name.",
    ],
  };
}
