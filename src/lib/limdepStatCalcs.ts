// ---------------------------------------------------------------------------------------------------- econ-count

export function econCountCalc(read: Read): StatOutput {
  const t = readTable(read);
  if ("error" in t) return refuse(t.error);
  const { data } = t;
  let spec = t.spec;
  const constant = (read("constant") || "yes") !== "no";
  const nb = read("model") === "nb2";
  const se = read("se") === "hc0" ? "hc0" : "classical";
  const expName = (read("exposure") ?? "").trim();
  const expKind = read("exposureKind") === "offset" ? "offset" : "exposure";
  let expCol = "";
  if (expName) {
    const ej = findColumn(data.names, expName);
    if (typeof ej !== "number") return refuse(`Exposure column: ${ej.error}`);
    expCol = data.names[ej];
    const depIdx = spec.dep === "" ? 0 : findColumn(data.names, spec.dep);
    if (typeof depIdx !== "number") return refuse(depIdx.error);
    if (depIdx === ej) return refuse(`${q(expCol)} is the response; it cannot also be the ${expKind} column.`);
    const preds: string[] = [];
    for (const pn of spec.preds) {
      if (pn === ".") {
        for (let j = 0; j < data.names.length; j++) if (j !== depIdx && j !== ej && !preds.includes(data.names[j])) preds.push(data.names[j]);
        continue;
      }
      const pj = findColumn(data.names, pn);
      if (typeof pj === "number" && pj === ej) return refuse(`${q(expCol)} is the ${expKind} column; it cannot also be a predictor.`);
      preds.push(pn);
    }
    spec = { dep: spec.dep === "" ? data.names[0] : spec.dep, preds: [...preds, expCol], text: spec.text };
  }
  const c = toCols(data, spec);
  if ("error" in c) return refuse(c.error);
  let offset: number[] | null = null;
  let X = c.X;
  let names = c.names;
  if (expCol) {
    const k = names.length - 1;
    const raw = X.map((r) => r[k]);
    X = X.map((r) => r.slice(0, k));
    names = names.slice(0, k);
    if (expKind === "exposure") {
      for (let i = 0; i < raw.length; i++) {
        if (!(raw[i] > 0)) return refuse(`Exposure column ${q(expCol)}, row ${c.rowNumbers[i]}: ${numText(raw[i])} is not positive. An exposure (time at risk, population) must be above 0; choose “offset” if the column is already a logarithm.`);
      }
      offset = raw.map(Math.log);
    } else offset = raw;
  }
  let r: CountResult;
  try {
    r = fitCount(c.y, X, names, { model: nb ? "nb2" : "poisson", constant, se, depName: c.depName, offset });
  } catch (e) {
    return fail(e, nb ? "negative binomial model" : "Poisson model");
  }
  const m = r.model;
  const lines: string[] = [];
  const title = nb ? "Negative binomial (NB2) regression" : "Poisson regression";
  lines.push(`${title} of ${m.depName} on ${list(names)} (n = ${intText(m.n)}, ${intText(r.nZero)} zero counts)`);
  if (expCol) {
    lines.push(
      expKind === "exposure"
        ? `Exposure: ${expCol}; ln ${expCol} enters as an offset with its coefficient fixed at 1, so the model is for the rate per unit of ${expCol}.`
        : `Offset: ${expCol}, entered as is with its coefficient fixed at 1.`,
    );
  }
  lines.push(statsLine(m));
  const ct = r.ct;
  const ctLine =
    `Overdispersion test (Cameron and Trivedi 1990, NB2 form; on the Poisson fit): auxiliary OLS through the origin of ((y − μ̂)² − y)/μ̂ on μ̂ gives ` +
    `α̂ = ${fmtFixed(ct.alpha, 4)} (SE ${fmtFixed(ct.se, 4)}), t = ${fmtFixed(ct.t, 2)}, one-sided ${pText(ct.p)}; Pearson χ²/df = ${fmtFixed(r.pearson / r.dfResid, 3)} (1 under the Poisson model).`;
  lines.push(ctLine);
  if (!nb) {
    lines.push(
      ct.p < 0.05 && ct.alpha > 0
        ? "The data are overdispersed at the 5% level: the Poisson coefficients stay consistent, but use robust (HC0) standard errors or the NB2 model."
        : "No evidence of overdispersion at the 5% level.",
    );
  } else if (r.alpha && r.lrAlpha) {
    const a = r.alpha;
    lines.push(
      `NB2 dispersion: α = ${fmtFixed(a.est, 4)} (SE ${fmtFixed(a.se, 4)}; 95% CI ${ci(a.lo, a.hi)}, from ln α), with Var(y | x) = μ + αμ².`,
      `LR test of α = 0 (NB2 against Poisson): LR = ${fmtFixed(r.lrAlpha.stat, 3)}, ${pText(r.lrAlpha.p)} (α = 0 is on the boundary, so p = ½·P(χ²₁ > LR)); Poisson log likelihood = ${fmtFixed(r.llPoisson, 3)}.`,
    );
  }
  lines.push(
    "Conventions: incidence-rate ratio IRR = exp(b); its SE by the delta method, exp(b)·SE(b); its 95% CI exponentiates the coefficient's interval; z and p are those of b. " +
      (constant ? `A constant is included (shown last; its IRR is the baseline rate${expCol && expKind === "exposure" ? ` per unit of ${expCol}` : ""} when every predictor is 0).` : "No constant."),
    `Standard errors: ${se === "hc0" ? "robust HC0 sandwich H⁻¹(Σ sᵢsᵢᵀ)H⁻¹, no small-sample factor (statsmodels cov_type=\"HC0\")" : "classical, the inverse of the observed information"}; z statistics and 95% intervals use the standard normal.`,
    `Pseudo R² is McFadden's 1 − ℓ/ℓ₀ against the constant-only ${nb ? "NB2 " : ""}model${expCol ? " with the same offset" : ""}; AIC = −2ℓ + 2k, BIC = −2ℓ + k ln N, k counting ${nb ? "α and " : ""}every coefficient.`,
    m.notes[0],
    ...readerNotes(data, c.notes),
  );
  if (r.irrOmitted.length) lines.push(`Not in the IRR table: ${r.irrOmitted.join(", ")}, whose exp(b) or interval is outside the representable range (|b| above 600; rescale or centre the predictors).`);
  const rows = [COEF_HEAD, ...m.terms.map((x) => termRow(x))];
  if (r.alpha) rows.push(["/alpha", fmtFixed(r.alpha.est, D), fmtFixed(r.alpha.se, D), "", "", ci(r.alpha.lo, r.alpha.hi)]);
  const tables: StatTable[] = [
    { label: `${title} coefficients (dependent variable: ${m.depName}; standard errors: ${m.seLabel})`, rows, align: ALIGN6 },
    { label: `Incidence-rate ratios exp(b) (dependent variable: ${m.depName})`, rows: [["Term", "IRR", "SE", "z", "p", "95% CI"], ...r.irr.map((x) => termRow(x))], align: ALIGN6 },
  ];
  return { text: lines.join("\n"), tables };
}

// ---------------------------------------------------------------------------------------------------- econ-tobit

export function econTobitCalc(read: Read): StatOutput {
  const t = readTable(read);
  if ("error" in t) return refuse(t.error);
  const lo = optionalNumber(read("lower"), "Lower limit");
  if (lo !== null && typeof lo === "object") return refuse(lo.error);
  const hi = optionalNumber(read("upper"), "Upper limit");
  if (hi !== null && typeof hi === "object") return refuse(hi.error);
  if (lo === null && hi === null) return refuse("Lower limit and Upper limit are both blank: tobit needs at least one censoring limit (0 for a corner at zero).");
  const constant = (read("constant") || "yes") !== "no";
  const c = toCols(t.data, t.spec);
  if ("error" in c) return refuse(c.error);
  let r;
  try {
    r = fitTobit(c.y, c.X, c.names, { lower: lo, upper: hi, constant, depName: c.depName });
  } catch (e) {
    return fail(e, "tobit model");
  }
  const m = r.model;
  const L = lo !== null ? numText(lo) : "";
  const U = hi !== null ? numText(hi) : "";
  const unc = lo !== null && hi !== null ? `${L} < y < ${U}` : lo !== null ? `y > ${L}` : `y < ${U}`;
  const counts = [
    lo !== null ? `${intText(r.nLeft)} left-censored at ${L}` : "",
    `${intText(r.nUncensored)} uncensored`,
    hi !== null ? `${intText(r.nRight)} right-censored at ${U}` : "",
  ].filter(Boolean);
  const s = r.sigma;
  const lines = [
    `Tobit regression of ${m.depName} on ${list(c.names)} (n = ${intText(m.n)}: ${counts.join(", ")})`,
    statsLine(m),
    `σ (standard deviation of the latent error) = ${fmtFixed(s.est, D)} (SE ${fmtFixed(s.se, D)}; 95% CI ${ci(s.lo, s.hi)}).`,
    `Conventions: latent y* = xβ + ε, ε ~ N(0, σ²); the observed y equals y* between the limits, and ${[lo !== null ? `a value at or below ${L} is censored at ${L}` : "", hi !== null ? `a value at or above ${U} is censored at ${U}` : ""].filter(Boolean).join(", and ")}. The coefficients are effects on the latent y* (∂E[y*]/∂x = β).`,
    `Marginal effects are AVERAGES over the sample (each observation's effect, then the mean; not at the means of x): ∂E[y]/∂x on the observed, censored outcome = β·P(${unc}); ∂E[y | ${unc}]/∂x conditional on being uncensored; ∂P(${unc})/∂x on the probability of being uncensored. Delta-method standard errors (analytic Jacobian in β and σ).`,
    "Standard errors: classical, the inverse of the observed information (σ by the delta method); z statistics and 95% intervals use the standard normal. Pseudo R² is McFadden's against the constant-only tobit.",
    m.notes[0],
    ...readerNotes(t.data, c.notes),
  ];
  const coefRows = [COEF_HEAD, ...m.terms.map((x) => termRow(x)), ["/sigma", fmtFixed(s.est, D), fmtFixed(s.se, D), "", "", ci(s.lo, s.hi)]];
  const ameRows: string[][] = [["Term", "∂E[y]/∂x", `∂E[y | ${unc}]/∂x`, `∂P(${unc})/∂x`]];
  for (const a of r.ame) {
    ameRows.push([a.name, fmtFixed(a.unconditional.coef, D), fmtFixed(a.conditional.coef, D), fmtFixed(a.probability.coef, D)]);
    ameRows.push(["", `(${fmtFixed(a.unconditional.se, D)})`, `(${fmtFixed(a.conditional.se, D)})`, `(${fmtFixed(a.probability.se, D)})`]);
  }
  const tables: StatTable[] = [
    { label: `Tobit coefficients (effects on the latent ${m.depName}*; standard errors: ${m.seLabel})`, rows: coefRows, align: ALIGN6 },
    {
      label: `Average marginal effects (dependent variable: ${m.depName})`,
      rows: ameRows,
      align: ["left", "right", "right", "right"],
      note: "Delta-method standard errors in parentheses.",
    },
  ];
  return { text: lines.join("\n"), tables };
}

// ---------------------------------------------------------------------------------------------------- econ-heckman

export function econHeckmanCalc(read: Read): StatOutput {
  const parsed = parseRegData(read("data"));
  if (!parsed.ok) return refuse(parsed.reason);
  const data = parsed.data;
  const outSpec = parseSpec(read("spec"));
  if ("error" in outSpec) return refuse(`Outcome equation: ${outSpec.error}`);
  const selText = (read("selection") ?? "").trim();
  if (!selText) return refuse("Selection equation: write it as “s ~ z1 + z2”, where s is 1 for a row whose outcome is observed and 0 otherwise.");
  const selSpec = parseSpec(selText);
  if ("error" in selSpec) return refuse(`Selection equation: ${selSpec.error}`);
  if (outSpec.dep === "") return refuse("Outcome equation: name the outcome, as in “wage ~ educ + exper” (the selected rows only need it).");
  // The two equations name each other's response: the indicator never enters the outcome equation (it is 1 in every
  // selected row) and the outcome never enters the selection equation (it is missing where s = 0).
  const oDep = findColumn(data.names, outSpec.dep);
  if (typeof oDep !== "number") return refuse(`Outcome equation: ${oDep.error}`);
  const sDep = findColumn(data.names, selSpec.dep);
  if (typeof sDep !== "number") return refuse(`Selection equation: ${sDep.error}`);
  if (oDep === sDep) return refuse(`${q(data.names[oDep])} cannot be both the outcome and the selection indicator.`);
  const expand = (sp: RegSpec, depIdx: number, other: number, what: string): RegSpec | { error: string } => {
    const preds: string[] = [];
    for (const pn of sp.preds) {
      if (pn === ".") {
        for (let j = 0; j < data.names.length; j++) if (j !== depIdx && j !== other && !preds.includes(data.names[j])) preds.push(data.names[j]);
        continue;
      }
      const pj = findColumn(data.names, pn);
      if (typeof pj === "number" && pj === other) {
        return { error: `${what}: ${q(data.names[pj])} is the ${what === "Outcome equation" ? "selection indicator" : "outcome"}; it cannot also be a predictor here.` };
      }
      preds.push(pn);
    }
    return { ...sp, preds };
  };
  const outSpecX = expand(outSpec, oDep, sDep, "Outcome equation");
  if ("error" in outSpecX) return refuse(outSpecX.error);
  const selSpecX = expand(selSpec, sDep, oDep, "Selection equation");
  if ("error" in selSpecX) return refuse(selSpecX.error);
  // 1. The selection equation on every row (s and z present).
  const sel = toCols(data, selSpecX);
  if ("error" in sel) return refuse(`Selection equation: ${sel.error}`);
  for (let i = 0; i < sel.y.length; i++) {
    if (sel.y[i] !== 0 && sel.y[i] !== 1) return refuse(`Selection indicator ${q(sel.depName)}, row ${sel.rowNumbers[i]}: ${numText(sel.y[i])} is not 0 or 1 (1 = the outcome is observed).`);
  }
  // 2. The outcome equation on the selected rows only.
  const selectedRows = sel.rowNumbers.filter((_, i) => sel.y[i] === 1);
  const outData: RegDataset = { ...data, rows: selectedRows.map((rn) => data.rows[rn - 1]) };
  const out = toCols(outData, outSpecX);
  if ("error" in out) return refuse(`Outcome equation (selected rows): ${out.error}`);
  // A selected row with a missing outcome or regressor leaves both equations.
  const keptOut = new Set(out.rowNumbers.map((k) => selectedRows[k - 1]));
  const dropped = selectedRows.filter((rn) => !keptOut.has(rn));
  const keepSel = sel.rowNumbers.map((rn, i) => sel.y[i] === 0 || keptOut.has(rn));
  const s = sel.y.filter((_, i) => keepSel[i]);
  const Z = sel.X.filter((_, i) => keepSel[i]);
  let r;
  try {
    r = fitHeckman({ s, Z, zNames: sel.names, selName: sel.depName, y: out.y, X: out.X, xNames: out.names, depName: out.depName });
  } catch (e) {
    return fail(e, "Heckman two-step model");
  }
  const m = r.model;
  const lam = r.lambda;
  const lines = [
    `Heckman selection model, two-step: ${m.depName} on ${list(out.names)}; selection: ${sel.depName} on ${list(sel.names)} (n = ${intText(r.n)}: ${intText(r.nSelected)} selected, ${intText(r.n - r.nSelected)} not selected)`,
    `ρ = ${fmtFixed(r.rho, 4)}, σ = ${fmtFixed(r.sigma, 4)}, λ coefficient = ρσ = ${fmtFixed(lam.coef, D)} (SE ${fmtFixed(lam.se, D)}); ${r.wald.df > 0 ? `Wald χ²(${r.wald.df}) = ${fmtFixed(r.wald.stat, 3)}, ${pText(r.wald.p)} (outcome predictors); ` : ""}probit log likelihood = ${fmtFixed(r.probitLl, 3)}.`,
    `Test of no selection bias (H₀: ρ = 0): z on λ = ${fmtFixed(lam.stat, 2)}, ${pText(lam.p)}.`,
    "Method (Wooldridge, Econometric Analysis of Cross Section and Panel Data, 2nd ed., 2010, §19.6): (1) probit of the selection indicator on z by maximum likelihood; (2) λᵢ = φ(zᵢγ̂)/Φ(zᵢγ̂), the inverse Mills ratio, for each selected row; (3) OLS of the outcome on x and λ over the selected rows.",
    "Corrected standard errors (Heckman 1979): V = σ²(X*ᵀX*)⁻¹[X*ᵀ(I − ρ²Δ)X* + ρ²(X*ᵀΔZ)V_γ(ZᵀΔX*)](X*ᵀX*)⁻¹ with X* = [x, λ, 1], Δ = diag(δᵢ), δᵢ = λᵢ(λᵢ + zᵢγ̂), σ² = eᵀe/n₁ + b_λ²·mean(δ), ρ = b_λ/σ, V_γ the probit's inverse information. The usual OLS standard errors of step 3 are not valid and are not shown.",
    "Maximum likelihood (full-information) estimation of the selection model is not offered: only the two-step estimator.",
  ];
  if (r.truncated) lines.push(`The two-step ρ fell outside [−1, 1]; it is truncated to ${fmtFixed(r.rho, 0)} and σ is set to |b_λ| (a sign that the model is misspecified or the exclusion restrictions are weak).`);
  if (r.excluded.length) lines.push(`Exclusion restriction${r.excluded.length === 1 ? "" : "s"}: ${r.excluded.join(", ")} enter${r.excluded.length === 1 ? "s" : ""} the selection equation but not the outcome equation.`);
  else lines.push("WARNING: every selection variable is also in the outcome equation, so the model is identified only by the nonlinearity of λ (functional form); estimates are fragile. Add a variable that affects selection but not the outcome.");
  if (dropped.length) lines.push(`${intText(dropped.length)} selected row${dropped.length === 1 ? "" : "s"} (data row${dropped.length === 1 ? "" : "s"} ${dropped.slice(0, 8).join(", ")}${dropped.length > 8 ? ", …" : ""}) had a missing outcome or regressor and ${dropped.length === 1 ? "was" : "were"} dropped from BOTH equations.`);
  lines.push("Conventions: constants in both equations (shown last); z statistics and 95% intervals use the standard normal.", ...readerNotes(data, [...sel.notes, ...out.notes.map((x) => `Outcome equation: ${x}`)]));
  const tables: StatTable[] = [
    { label: `Outcome equation (dependent variable: ${m.depName}; two-step corrected standard errors)`, rows: [COEF_HEAD, ...m.terms.map((x) => termRow(x))], align: ALIGN6 },
    { label: `Selection equation: probit of ${sel.depName} (classical standard errors)`, rows: [COEF_HEAD, ...r.selection.map((x) => termRow(x))], align: ALIGN6 },
  ];
  return { text: lines.join("\n"), tables };
}

// ---------------------------------------------------------------------------------------------------- econ-ordered

export function econOrderedCalc(read: Read): StatOutput {
  const t = readTable(read);
  if ("error" in t) return refuse(t.error);
  const link = read("link") === "probit" ? "probit" : "logit";
  const c = toCols(t.data, t.spec);
  if ("error" in c) return refuse(c.error);
  let r;
  try {
    r = fitOrdered(c.y, c.X, c.names, link, { depName: c.depName });
  } catch (e) {
    return fail(e, `ordered ${link} model`);
  }
  const m = r.model;
  const title = link === "logit" ? "Ordered logit" : "Ordered probit";
  const cat = r.categories.map(numText);
  const lines = [
    `${title} regression of ${m.depName} (${r.categories.length} ordered categories: ${cat.join(" < ")}) on ${list(c.names)} (n = ${intText(m.n)})`,
    statsLine(m),
    `Conventions: P(${m.depName} ≤ category j | x) = F(κⱼ − xβ) with F the ${link === "logit" ? "logistic" : "standard normal"} CDF and ${r.categories.length - 1} increasing cut points κ₁ < κ₂ < …; no constant (the cut points carry the level, as statsmodels OrderedModel and Stata). A positive coefficient shifts probability towards the higher categories${link === "logit" ? "; exp(b) is the proportional odds ratio" : ""}.`,
    "Standard errors: classical, the inverse of the observed information; z statistics and 95% intervals use the standard normal. Pseudo R² is McFadden's against the cut-points-only model.",
    "Marginal effects on each category's probability are not offered here.",
    m.notes[0],
    ...readerNotes(t.data, c.notes),
  ];
  const cutRows = [["Cut point", "Estimate", "SE", "95% CI"], ...r.cuts.map((x, j) => [`${x.name} (${cat[j]} | ${cat[j + 1]})`, fmtFixed(x.coef, D), fmtFixed(x.se, D), ci(x.ciLo, x.ciHi)])];
  const shareRows = [
    ["Category", "Observed", "Observed share", "Mean predicted probability"],
    ...r.categories.map((v, j) => [numText(v), intText(r.counts[j]), fmtFixed(r.counts[j] / m.n, 4), fmtFixed(r.meanProb[j], 4)]),
  ];
  const tables: StatTable[] = [
    { label: `${title} coefficients (dependent variable: ${m.depName}; standard errors: ${m.seLabel})`, rows: [COEF_HEAD, ...m.terms.map((x) => termRow(x))], align: ALIGN6 },
    { label: "Cut points κⱼ", rows: cutRows, align: ["left", "right", "right", "right"] },
    { label: "Observed shares and mean predicted probabilities", rows: shareRows, align: ["left", "right", "right", "right"] },
  ];
  return { text: lines.join("\n"), tables };
}

// ---------------------------------------------------------------------------------------------------- econ-mlogit

export function econMlogitCalc(read: Read): StatOutput {
  const t = readTable(read);
  if ("error" in t) return refuse(t.error);
  const base = optionalNumber(read("base"), "Base category");
  if (base !== null && typeof base === "object") return refuse(base.error);
  const c = toCols(t.data, t.spec);
  if ("error" in c) return refuse(c.error);
  let r;
  try {
    r = fitMnl(c.y, c.X, c.names, { base, depName: c.depName });
  } catch (e) {
    return fail(e, "multinomial logit model");
  }
  const dep = c.depName;
  const lab = (cat: number, term: string): string => `${dep} = ${numText(cat)}: ${term}`;
  const lr = r.stats.find((s) => s.label.startsWith("LR χ²"));
  const pLR = r.stats.find((s) => s.label === "Prob > χ²");
  const pr2 = r.stats.find((s) => s.label === "Pseudo R²")!;
  const aic = r.stats.find((s) => s.label === "AIC")!;
  const bic = r.stats.find((s) => s.label === "BIC")!;
  const lines = [
    `Multinomial logit regression of ${dep} (${r.categories.length} categories: ${r.categories.map((v, j) => `${numText(v)} (n = ${intText(r.counts[j])})`).join(", ")}) on ${list(c.names)} (n = ${intText(r.n)}); base category ${numText(r.base)}`,
    `Log likelihood = ${fmtFixed(r.ll, 3)}; ${lr && pLR ? `${lr.label} = ${fmtFixed(lr.value, 3)}, ${pText(pLR.value)}; ` : ""}McFadden pseudo R² = ${fmtFixed(pr2.value, 4)}; AIC = ${fmtFixed(aic.value, 3)}; BIC = ${fmtFixed(bic.value, 3)}.`,
    `Conventions: P(${dep} = j | x) = exp(xβⱼ)/Σₖ exp(xβₖ) with β = 0 for the base category ${numText(r.base)}; each equation's coefficients are log odds of category j against the base. Relative-risk ratio RRR = exp(b) (SE exp(b)·SE(b), interval from the coefficient's interval). A constant in every equation (shown last).`,
    "Average marginal effects: ∂P(category)/∂x averaged over the sample, for EVERY category including the base (they sum to 0 across categories); a 0/1 predictor treated as a continuous derivative (statsmodels get_margeff at=\"overall\", method=\"dydx\"); delta-method standard errors from an analytic Jacobian.",
    "Standard errors: classical, the inverse of the observed information; z statistics and 95% intervals use the standard normal.",
    `Maximum likelihood by Newton–Raphson (concave; at most ${LIMDEP_MAX_ITER} iterations): converged in ${r.iterations} iteration${r.iterations === 1 ? "" : "s"}.`,
    ...readerNotes(t.data, c.notes),
  ];
  if (r.rrrOmitted.length) lines.push(`Not in the RRR table: ${r.rrrOmitted.join(", ")}, whose exp(b) or interval is outside the representable range (|b| above 600; rescale or centre the predictors).`);
  const coefRows = [COEF_HEAD, ...r.equations.flatMap((e) => e.terms.map((x) => termRow(x, lab(e.category, x.name))))];
  const rrrRows = [["Term", "RRR", "SE", "z", "p", "95% CI"], ...r.rrr.flatMap((e) => e.terms.map((x) => termRow(x, lab(e.category, x.name))))];
  const ameRows = [["Term", "dP/dx", "SE", "z", "p", "95% CI"], ...r.ame.flatMap((e) => e.terms.map((x) => termRow(x, `P(${dep} = ${numText(e.category)}): ${x.name}`)))];
  const tables: StatTable[] = [
    { label: `Multinomial logit coefficients (base: ${dep} = ${numText(r.base)})`, rows: coefRows, align: ALIGN6 },
    { label: `Relative-risk ratios exp(b) (base: ${dep} = ${numText(r.base)})`, rows: rrrRows, align: ALIGN6 },
    { label: "Average marginal effects on each category's probability", rows: ameRows, align: ALIGN6 },
  ];
  return { text: lines.join("\n"), tables };
}

