/** KO^{-q}(pt), q any integer: ℤ, ℤ/2, ℤ/2, 0, ℤ, 0, 0, 0 by q mod 8. */
export const KO_POINT = ["ℤ", "ℤ/2", "ℤ/2", "0", "ℤ", "0", "0", "0"] as const;

export function koOfPoint(q: number): string {
  const r = ((q % 8) + 8) % 8;
  return KO_POINT[r];
}

/** Direct sum of group names, dropping zeros. */
export function directSum(...gs: string[]): string {
  const nz = gs.filter((g) => g !== "0");
  return nz.length ? nz.join(" ⊕ ") : "0";
}

// ---------------------------------------------------------------------------
// Adams φ(n) and the independent Atiyah–Hirzebruch count
// ---------------------------------------------------------------------------

/** φ(n) = #{s : 0 < s ≤ n, s ≡ 0, 1, 2, 4 (mod 8)} — closed form, O(1). */
export function adamsPhi(n: number): number {
  if (!Number.isFinite(n) || n <= 0) return 0;
  const full = Math.floor(n / 8);
  let c = full * 4;
  for (let s = full * 8 + 1; s <= n; s++) {
    const r = s % 8;
    if (r === 0 || r === 1 || r === 2 || r === 4) c++;
  }
  return c;
}

/**
 * Cellular cohomology H^q(ℝPⁿ; G) for G = ℤ or ℤ/2, from the cochain complex
 * G → G → … → G whose coboundary C^q → C^{q+1} is multiplication by
 * 1 + (−1)^{q+1}: 0 for q even, 2 for q odd. Returns "ℤ", "ℤ/2" or "0".
 */
export function rpCohomology(n: number, q: number, coeff: "Z" | "Z/2"): string {
  if (q < 0 || q > n) return "0";
  const out = q < n ? (q % 2 === 1 ? 2 : 0) : 0;     // δ_q
  const inc = q > 0 ? ((q - 1) % 2 === 1 ? 2 : 0) : 0; // δ_{q-1}
  if (coeff === "Z/2") return "ℤ/2"; // ×2 is zero on ℤ/2, so every cochain is a cocycle and none a coboundary
  // Over ℤ: ×2 is injective, so ker δ_q is ℤ only when δ_q = 0.
  if (out !== 0) return "0";
  return inc === 2 ? "ℤ/2" : "ℤ";
}

/**
 * Second route: the nonzero reduced E₂ entries H̃^q(ℝPⁿ; KO^{-q}(pt)),
 * 0 < q ≤ n, computed from the cochain complex above (not from φ's formula).
 */
export function ahssKoEntriesRP(n: number): { q: number; group: string }[] {
  const out: { q: number; group: string }[] = [];
  for (let q = 1; q <= n; q++) {
    const c = koOfPoint(q);
    if (c === "0") continue;
    const g = rpCohomology(n, q, c === "ℤ" ? "Z" : "Z/2");
    if (g !== "0") out.push({ q, group: g });
  }
  return out;
}

