# --- Bootstrap -----------------------------------------------------------------------------------------------------

def bootstrap(instr, f):
    ins = sorted(instr, key=lambda x: x[0])
    ts, zs = [], []

    def zat(s):
        if s <= ts[0]:
            return zs[0]
        for i in range(1, len(ts)):
            if s <= ts[i]:
                return zs[i - 1] + (zs[i] - zs[i - 1]) * (s - ts[i - 1]) / (ts[i] - ts[i - 1])
        return zs[-1]

    for t, cpn, price in ins:
        m = round(t * f)
        c = 100 * cpn / f
        tp = ts[-1] if ts else 0.0
        zp = zs[-1] if zs else None

        def g(z):
            pv = 0.0
            for k in range(1, m + 1):
                s = k / f
                if ts and s <= tp + 1e-12:
                    zz = zat(s)
                elif not ts:
                    zz = z
                else:
                    zz = zp + (z - zp) * (s - tp) / (t - tp)
                pv += (c + (100 if k == m else 0)) * math.exp(-zz * s)
            return pv - price

        z = brentq(g, -0.5, 2.0, xtol=1e-16, rtol=1e-15, maxiter=500)
        ts.append(t)
        zs.append(z)
    rows = []
    for i, (t, z) in enumerate(zip(ts, zs)):
        df = math.exp(-z * t)
        t0 = ts[i - 1] if i else 0.0
        df0 = math.exp(-zs[i - 1] * t0) if i else 1.0
        rows.append(dict(t=t, z=z, df=df, zPeriodic=f * (df ** (-1 / (f * t)) - 1),
                         fwd=(z * t - (zs[i - 1] * t0 if i else 0)) / (t - t0),
                         fwdPeriodic=f * ((df0 / df) ** (1 / (f * (t - t0))) - 1)))
    return rows


