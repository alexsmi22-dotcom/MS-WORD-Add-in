# --- Nelson-Siegel / Svensson -------------------------------------------------------------------------------------

def L1(x):
    return -np.expm1(-x) / x


def L2(x):
    return L1(x) - np.exp(-x)


def prof(ts, ys, lam):
    cols = [np.ones_like(ts), L1(ts / lam[0]), L2(ts / lam[0])]
    if len(lam) > 1:
        cols.append(L2(ts / lam[1]))
    X = np.column_stack(cols)
    beta, *_ = np.linalg.lstsq(X, ys, rcond=None)
    r = ys - X @ beta
    return beta, float(r @ r)


LO, HI = math.log(0.05), math.log(50)


def fit_ns(ts, ys):
    ts, ys = np.array(ts, float), np.array(ys, float)
    grid = np.linspace(LO, HI, 4001)
    s = [prof(ts, ys, [math.exp(u)])[1] for u in grid]
    i = int(np.argmin(s))
    a, b = grid[max(0, i - 1)], grid[min(len(grid) - 1, i + 1)]
    r = minimize_scalar(lambda u: prof(ts, ys, [math.exp(u)])[1], bounds=(a, b), method="bounded",
                        options=dict(xatol=1e-13, maxiter=1000))
    lam = [math.exp(r.x)]
    beta, sse = prof(ts, ys, lam)
    return dict(beta=beta.tolist(), lam=lam, sse=sse, fitted=[float(v) for v in
                                                              (beta[0] + beta[1] * L1(ts / lam[0]) + beta[2] * L2(ts / lam[0]))])


def fit_sv(ts, ys):
    ts, ys = np.array(ts, float), np.array(ys, float)
    grid = np.linspace(LO, HI, 301)
    best = (math.inf, None)
    for u1 in grid:
        for u2 in grid:
            if u2 - u1 < math.log(2) - 1e-12:
                continue
            s = prof(ts, ys, [math.exp(u1), math.exp(u2)])[1]
            if s < best[0]:
                best = (s, (u1, u2))

    def obj(u):
        u1, u2 = u
        pen = 0.0
        if u2 - u1 < math.log(2):
            pen += 1e6 * (math.log(2) - (u2 - u1))
        if u1 < LO or u2 > HI:
            pen += 1e6
        u1 = min(max(u1, LO), HI)
        u2 = min(max(u2, u1 + math.log(2)), HI)
        return prof(ts, ys, [math.exp(u1), math.exp(u2)])[1] + pen

    r = minimize(obj, np.array(best[1]), method="Nelder-Mead", options=dict(xatol=1e-12, fatol=1e-18, maxiter=20000))
    u1, u2 = r.x
    u1 = min(max(u1, LO), HI)
    u2 = min(max(u2, u1 + math.log(2)), HI)
    lam = [math.exp(u1), math.exp(u2)]
    beta, sse = prof(ts, ys, lam)
    if best[0] < sse:
        lam = [math.exp(best[1][0]), math.exp(best[1][1])]
        beta, sse = prof(ts, ys, lam)
    fitted = beta[0] + beta[1] * L1(ts / lam[0]) + beta[2] * L2(ts / lam[0]) + beta[3] * L2(ts / lam[1])
    return dict(beta=beta.tolist(), lam=lam, sse=sse, fitted=[float(v) for v in fitted])


