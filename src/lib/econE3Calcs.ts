// Worked default for the event study: 200 trading days (weekdays from January 2, 2024), a market and two firms,
// generated by a fixed-seed LCG + Box–Muller and rounded to five decimals.

function eventDefaultTable(): string {
  let seed = 20240102;
  const u = (): number => {
    seed = (seed * 1103515245 + 12345) % 2147483648;
    return (seed + 0.5) / 2147483648;
  };
  const gauss = (): number => Math.sqrt(-2 * Math.log(u())) * Math.cos(2 * Math.PI * u());
  const lines = ["Date\tMarket\tAcme\tBorealis"];
  let day = civilDay(2024, 1, 2);
  const acmeEvent = civilDay(2024, 8, 1);
  const borEvent = civilDay(2024, 8, 19);
  const r5 = (v: number): string => (Math.round(v * 1e5) / 1e5).toFixed(5);
  for (let i = 0; i < 200; i++) {
    // Weekdays only (day 0 of the civil count is a Thursday: 1970-01-01).
    while ((((day + 4) % 7) + 7) % 7 === 0 || (((day + 4) % 7) + 7) % 7 === 6) day++;
    const m = 0.0004 + 0.009 * gauss();
    let a = 0.0002 + 1.2 * m + 0.012 * gauss();
    let b = -0.0001 + 0.8 * m + 0.01 * gauss();
    if (day === acmeEvent) a += 0.035;
    if (day === borEvent) b -= 0.025;
    const { y, m: mo, d } = civilFromDay(day);
    const iso = `${y}-${String(mo).padStart(2, "0")}-${String(d).padStart(2, "0")}`;
    lines.push([iso, r5(m), r5(a), r5(b)].join("\t"));
    day++;
  }
  return lines.join("\n");
}

