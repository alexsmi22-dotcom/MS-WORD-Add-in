/** idx-price: price indexes. */
export function idxPriceCalc(read: Read): StatOutput {
  const get = (k: string): string => String(read(k) ?? "");
  const p = parsePriceTable(get("data"));
  if (!p.ok) return refuse(p.reason);
  const tbl = p.table;
  const fRaw = get("formula") || "all";
  if (fRaw !== "all" && !INDEX_FORMULAS.includes(fRaw as IndexFormula)) return refuse(`Unknown index ${q(fRaw)}.`);
  const formulas: IndexFormula[] = fRaw === "all" ? INDEX_FORMULAS : [fRaw as IndexFormula];
  const mRaw = get("method") || "fixed";
  if (mRaw !== "fixed" && mRaw !== "chained") return refuse(`Unknown comparison ${q(mRaw)}.`);
  const chained = mRaw === "chained";
  const baseRaw = get("base").trim();
  let r = 0;
  if (baseRaw) {
    r = tbl.periods.findIndex((x) => x.toLowerCase() === baseRaw.toLowerCase());
    if (r < 0) return refuse(`No period is named ${q(baseRaw)}; the periods are ${tbl.periods.map(q).join(", ")}.`);
  }
  const series = formulas.map((f) => rebase(indexSeries(tbl, f, chained), r));
  for (const [j, s] of series.entries()) {
    if (s.some((v) => !Number.isFinite(v) || v <= 0)) return refuse(`The ${INDEX_NAMES[formulas[j]]} index is not a finite positive number for these prices (an extreme scale).`);
  }
  const rows: string[][] = [["Period", ...formulas.map((f) => INDEX_NAMES[f])]];
  tbl.periods.forEach((per, t) => rows.push([per, ...series.map((s) => fmtFixed(s[t], 3))]));
  const lines: string[] = [];
  lines.push(`Price index${formulas.length > 1 ? "es" : ""}: ${tbl.items.length} item${tbl.items.length === 1 ? "" : "s"}, ${tbl.periods.length} periods, ${chained ? "chained" : "fixed base"}, ${tbl.periods[r]} = 100`);
  const last = tbl.periods.length - 1;
  lines.push(formulas.map((f, j) => `${INDEX_NAMES[f]} ${tbl.periods[last]}: ${fmtFixed(series[j][last], 3)}`).join(" · "));
  lines.push("");
  lines.push(
    "Conventions (ILO/IMF CPI Manual, 2004), comparing period t with period s: Laspeyres Σpₜqₛ/Σpₛqₛ; Paasche Σpₜqₜ/Σpₛqₜ; Fisher √(Laspeyres × Paasche); " +
      "Törnqvist exp Σ ½(wₛ + wₜ) ln(pₜ/pₛ) with expenditure shares w = pq/Σpq.",
  );
  lines.push(
    chained
      ? "Chained: each period is compared with the one before and the links are multiplied, so the weights move every period."
      : `Fixed base: every period is compared directly with ${tbl.periods[0]}, whose prices and quantities are the reference.`,
  );
  lines.push(`Rebased so ${tbl.periods[r]} = 100 (a rescaling; the weights are unchanged). Every item is priced in every period (matched items); zero quantities are allowed.`);
  lines.push(...tbl.notes);
  const colors = ["#0369a1", "#b45309", "#15803d", "#7c3aed"];
  const svg = buildPlotSvg(
    series.map((s, j) => ({ type: "line" as const, points: s.map((v, t) => ({ x: t + 1, y: v })), color: colors[j], label: INDEX_NAMES[formulas[j]] })),
    {
      width: 400,
      height: 260,
      title: "Price index",
      xlabel: "Period",
      ylabel: `Index (${tbl.periods[r]} = 100)`,
      // The periods by name at the whole-number ticks; a tick between two periods ("1.5") names nothing.
      xTickLabel: (v: number) => {
        const t = Math.round(v);
        return Math.abs(v - t) < 1e-9 && t >= 1 && t <= tbl.periods.length ? tbl.periods[t - 1] : "";
      },
    },
  );
  return {
    text: lines.join("\n"),
    reading: priceIndexReading(tbl.periods, r, formulas, series),
    tables: [{ label: "Price index", rows, align: ["left", ...formulas.map((): "right" => "right")] }],
    svg,
  };
}

/**
 * The plain-language reading of the price indexes: what the basket costs in the last period for every 100 it cost in
 * the base (the first period when the base is the last), by Fisher when it was computed, else the one formula, and
 * the spread across the formulas when there are several. Values as the table prints them (fmtFixed, 3 decimals).
 */
export function priceIndexReading(periods: string[], base: number, formulas: IndexFormula[], series: number[][]): string {
  const last = periods.length - 1;
  const c = last !== base ? last : 0;
  const j = formulas.includes("fisher") ? formulas.indexOf("fisher") : 0;
  const v = series[j][c];
  const shown = fmtFixed(v, 3);
  const dir = shown === fmtFixed(100, 3) ? "prices are unchanged" : v > 100 ? "prices are higher" : "prices are lower";
  const head =
    `By the ${INDEX_NAMES[formulas[j]]} index, the basket costs ${shown} in ${periods[c]} for every 100 it cost in ${periods[base]}, so ${dir}` +
    (c < base ? ` in ${periods[c]} than in ${periods[base]}` : "");
  if (formulas.length < 2) return `${head}.`;
  let lo = 0;
  let hi = 0;
  series.forEach((s, k) => {
    if (s[c] < series[lo][c]) lo = k;
    if (s[c] > series[hi][c]) hi = k;
  });
  if (fmtFixed(series[lo][c], 3) === fmtFixed(series[hi][c], 3)) return `${head}; all ${formulas.length} formulas agree.`;
  return `${head}; the ${formulas.length} formulas range from ${fmtFixed(series[lo][c], 3)} (${INDEX_NAMES[formulas[lo]]}) to ${fmtFixed(series[hi][c], 3)} (${INDEX_NAMES[formulas[hi]]}).`;
}

