# --- Treasury bills ------------------------------------------------------------------------------------------------

def tbill(settle, maturity, price=None, discount=None, treasury=False):
    s, m = qd(settle), qd(maturity)
    t = m - s
    P = price if price is not None else 100 * (1 - discount * t / 360)
    Byr = 365
    if treasury:
        end = s + ql.Period(1, ql.Years)
        for yy in (s.year(), s.year() + 1):
            if ql.Date.isLeap(yy) and s < ql.Date(29, 2, yy) <= end:
                Byr = 366
    if t <= Byr // 2:
        bey = (100 - P) / P * Byr / t
    else:
        a, b, c = t / (2 * Byr) - 0.25, t / Byr, (P - 100) / P
        bey = (-b + math.sqrt(b * b - 4 * a * c)) / (2 * a)
    return dict(settle=settle, maturity=maturity, price_in=price, discount_in=discount, treasury=treasury, days=t,
                price=P, discount=(100 - P) / 100 * 360 / t, moneyMarket=(100 - P) / P * 360 / t, bey=bey, yearDays=Byr)


