"""
Writes src/lib/usLifeTable2024.ts from the official CDC/NCHS data files of

    United States Life Tables, 2024. National Vital Statistics Reports, Vol. 75, No. 5 (August 25, 2026),
    by Elizabeth Arias, Jiaquan Xu and Betzaida Tejada-Vera. National Center for Health Statistics.
    Data files: https://ftp.cdc.gov/pub/Health_Statistics/NCHS/Publications/NVSR/75-05/Table01.xlsx (total),
    Table02.xlsx (males), Table03.xlsx (females).

Public domain (a work of the US federal government). Run by hand (it downloads the three files); not part of CI:

    ~/jurislab-oracle-venv/Scripts/python.exe -I scripts/forensic-lifetable-gen.py

It keeps the qx column (ages 0-99 and the open "100 and over" row, qx = 1) to 9 significant digits (the data files
hold float32 values, about 7 significant digits) and e100 (the published expectation of life at 100) for each table,
and prints the self-checks: lx recomputed from qx against the files' lx, and ex recomputed (Lx = lx - dx/2 for ages
1-99, L100 = l100 x e100) against the files' ex.
"""
import io
import re
import sys
import tempfile
import urllib.request
import zipfile
import xml.etree.ElementTree as ET
from pathlib import Path

BASE = "https://ftp.cdc.gov/pub/Health_Statistics/NCHS/Publications/NVSR/75-05/"
FILES = {"total": "Table01.xlsx", "male": "Table02.xlsx", "female": "Table03.xlsx"}
NS = {"m": "http://schemas.openxmlformats.org/spreadsheetml/2006/main"}
OUT = Path(__file__).resolve().parent.parent / "src" / "lib" / "usLifeTable2024.ts"


def read_xlsx(data: bytes):
    z = zipfile.ZipFile(io.BytesIO(data))
    ss = []
    if "xl/sharedStrings.xml" in z.namelist():
        r = ET.fromstring(z.read("xl/sharedStrings.xml"))
        for si in r.findall("m:si", NS):
            ss.append("".join(t.text or "" for t in si.iter("{%s}t" % NS["m"])))
    sheet = sorted(n for n in z.namelist() if n.startswith("xl/worksheets/sheet"))[0]
    r = ET.fromstring(z.read(sheet))
    rows = []
    for row in r.iter("{%s}row" % NS["m"]):
        cells = {}
        for c in row.findall("m:c", NS):
            col = re.match(r"[A-Z]+", c.get("r")).group(0)
            v = c.find("m:v", NS)
            if v is None:
                cells[col] = ""
            elif c.get("t") == "s":
                cells[col] = ss[int(v.text)]
            else:
                cells[col] = v.text
        rows.append(cells)
    return rows


def table(name: str):
    with urllib.request.urlopen(BASE + FILES[name], timeout=60) as resp:
        rows = read_xlsx(resp.read())
    title = rows[0]["A"]
    data = []
    for r in rows:
        a = r.get("A", "")
        m = re.match(r"^(\d+)\D+(\d+)$", a.strip())
        if m and int(m.group(2)) == int(m.group(1)) + 1:
            data.append((int(m.group(1)), float(r["B"]), float(r["C"]), float(r["G"])))
        elif a.strip().startswith("100 and over"):
            data.append((100, float(r["B"]), float(r["C"]), float(r["G"])))
    ages = [d[0] for d in data]
    assert ages == list(range(101)), (name, ages[:3], ages[-3:])
    return title, data


def main():
    out = {}
    for name in FILES:
        title, data = table(name)
        assert "2024" in title, title
        qx = [float("%.9g" % d[1]) for d in data]
        assert qx[100] == 1.0
        e100 = float("%.6g" % data[100][3])
        # Self-checks.
        lx = [100000.0]
        for x in range(100):
            lx.append(lx[-1] * (1 - qx[x]))
        dl = max(abs(lx[x] - data[x][2]) for x in range(101))
        T = lx[100] * e100
        ex = [0.0] * 101
        ex[100] = e100
        for x in range(99, 0, -1):
            T += lx[x] - (lx[x] - lx[x + 1]) / 2
            ex[x] = T / lx[x]
        de = max(abs(ex[x] - data[x][3]) for x in range(1, 101))
        print(f"{name}: {title}; max |lx - file| = {dl:.4f}; max |ex - file| (ages 1-100) = {de:.5f}")
        out[name] = (qx, e100)

    lines = []
    lines.append("/**")
    lines.append(" * CDC/NCHS United States Life Tables, 2024: the qx column (probability of dying between ages x and x + 1) by single")
    lines.append(" * year of age, 0-99 and the open interval \"100 and over\" (qx = 1), for the total population, males and females.")
    lines.append(" * GENERATED by scripts/forensic-lifetable-gen.py from the official data files; do not edit by hand.")
    lines.append(" *")
    lines.append(" * Source: Arias E, Xu J, Tejada-Vera B. United States Life Tables, 2024. National Vital Statistics Reports, Vol. 75,")
    lines.append(" * No. 5 (August 25, 2026). Hyattsville, MD: National Center for Health Statistics. Tables 1 (total), 2 (males) and")
    lines.append(" * 3 (females); data files ftp.cdc.gov/pub/Health_Statistics/NCHS/Publications/NVSR/75-05/Table01.xlsx, Table02.xlsx,")
    lines.append(" * Table03.xlsx, accessed 2026-10-27. Public domain (a work of the US federal government).")
    lines.append(" *")
    lines.append(" * Values kept to 9 significant digits (the files hold float32 values). e100 is the published expectation of life at")
    lines.append(" * age 100 (column ex of the \"100 and over\" row). Checked in src/lib/__tests__/forensic.test.ts against the printed")
    lines.append(" * report (qx to 6 decimals, lx and ex) and by recomputing lx and ex from qx.")
    lines.append(" */")
    lines.append("export const US_LIFE_2024_SOURCE =")
    lines.append('  "CDC/NCHS, United States Life Tables, 2024, National Vital Statistics Reports Vol. 75, No. 5 (August 25, 2026), Tables 1–3; data files accessed October 27, 2026";')
    lines.append('export const US_LIFE_2024_SHORT = "CDC NVSR Vol. 75, No. 5 (US Life Tables, 2024)";')
    lines.append("")
    lines.append("export type UsLifeSex = \"total\" | \"male\" | \"female\";")
    lines.append("")
    lines.append("export const US_LIFE_2024: Record<UsLifeSex, { qx: readonly number[]; e100: number }> = {")
    for name in FILES:
        qx, e100 = out[name]
        lines.append(f"  {name}: {{")
        lines.append(f"    e100: {e100!r},")
        lines.append("    qx: [")
        for k in range(0, 101, 6):
            lines.append("      " + ", ".join(repr(v) for v in qx[k:k + 6]) + ",")
        lines.append("    ],")
        lines.append("  },")
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("wrote", OUT)


if __name__ == "__main__":
    sys.exit(main())
