FREQ = {1: ql.Annual, 2: ql.Semiannual, 4: ql.Quarterly, 12: ql.Monthly}


def qd(s):
    y, m, d = map(int, s.split("-"))
    return ql.Date(d, m, y)


def iso(d):
    return "%04d-%02d-%02d" % (d.year(), d.month(), d.dayOfMonth())


def ql_schedule(settle, maturity, f):
    start = settle - ql.Period(2, ql.Years)
    return ql.Schedule(start, maturity, ql.Period(FREQ[f]), ql.NullCalendar(), ql.Unadjusted, ql.Unadjusted,
                       ql.DateGeneration.Backward, True)


def ql_case(c):
    settle, maturity, f = qd(c["settle"]), qd(c["maturity"]), c["freq"]
    ql.Settings.instance().evaluationDate = settle
    sched = ql_schedule(settle, maturity, f)
    if c["basis"] == "actact":
        dc = ql.ActualActual(ql.ActualActual.ISMA, sched)
    elif c["basis"] == "30360us":
        dc = ql.Thirty360(ql.Thirty360.USA)
    elif c["basis"] == "30e360":
        dc = ql.Thirty360(ql.Thirty360.European)
    else:
        raise ValueError(c["basis"])
    bond = ql.FixedRateBond(0, 100.0, sched, [c["rate"]], dc, ql.Unadjusted, c["redemption"])
    remaining = [cf for cf in bond.cashflows() if cf.date() > settle]
    dates = sorted({cf.date() for cf in remaining})
    comp = ql.Compounded if len(dates) > 1 else ql.SimpleThenCompounded
    y = c["yield"]
    fq = FREQ[f]
    clean = ql.BondFunctions.cleanPrice(bond, y, dc, comp, fq, settle)
    accrued = ql.BondFunctions.accruedAmount(bond, settle)
    dirty = clean + accrued  # the Python bindings have no yield overload of dirtyPrice
    rate = ql.InterestRate(y, dc, comp, fq)
    if len(dates) > 1:
        mac = ql.BondFunctions.duration(bond, rate, ql.Duration.Macaulay, settle)
    else:
        # QuantLib's Macaulay duration requires Compounded; for a single remaining flow it is its time.
        prev0 = ql.BondFunctions.previousCashFlowDate(bond, settle)
        mac = dc.yearFraction(settle, dates[0], prev0, dates[0])
    mod = ql.BondFunctions.duration(bond, rate, ql.Duration.Modified, settle)
    conv = ql.BondFunctions.convexity(bond, rate, settle)
    price_obj = ql.BondPrice(clean, ql.BondPrice.Clean)
    ysolved = ql.BondFunctions.bondYield(bond, price_obj, dc, comp, fq, settle, 1e-14, 1000, y)
    prev = ql.BondFunctions.previousCashFlowDate(bond, settle)
    nxt = ql.BondFunctions.nextCashFlowDate(bond, settle)
    return dict(c, source="QuantLib", clean=clean, dirty=dirty, accrued=accrued, macaulay=mac, modified=mod,
                convexity=conv, yieldFromClean=ysolved, prev=iso(prev), next=iso(nxt), N=len(dates))


# --- Excel transcription (independent of the TypeScript) ---------------------------------------------------------

def last_of_month(y, m):
    return ql.Date.endOfMonth(ql.Date(1, m, y)).dayOfMonth()


def days360_excel(d1, d2):
    """Excel basis 0 as LibreOffice scaddins ScaDate::setDay/getDiff counts it (analysishelper.cxx)."""
    if d1 == d2:
        return 0  # same day (the both-February-end rule alone would give -1)
    y1, m1, a = d1.year(), d1.month(), d1.dayOfMonth()
    y2, m2, b = d2.year(), d2.month(), d2.dayOfMonth()
    feb1 = m1 == 2 and a == last_of_month(y1, 2)
    feb2 = m2 == 2 and b == last_of_month(y2, 2)
    if a == 31 and b == 31:
        a, b = 30, 30
    elif a == 31:
        a = 30
    elif a == 30 and b == 31:
        b = 30
    elif feb1 and feb2:
        a = 30  # LibreOffice getDiff: D2 stays February's last day
    elif feb1:
        a = 30
    return 360 * (y2 - y1) + 30 * (m2 - m1) + (b - a)


def py_schedule(settle, maturity, f):
    eom = maturity.dayOfMonth() == last_of_month(maturity.year(), maturity.month())
    dates, k = [], 0
    while True:
        d = maturity - ql.Period(k * 12 // f, ql.Months)  # QuantLib clamps to month end
        if eom:
            d = ql.Date.endOfMonth(d)
        if d <= settle:
            return d, list(reversed(dates))
        dates.append(d)
        k += 1


def excel_price(c):
    settle, maturity, f = qd(c["settle"]), qd(c["maturity"]), c["freq"]
    prev, dates = py_schedule(settle, maturity, f)
    nxt = dates[0]
    b = c["basis"]
    if b == "30360us":
        A = days360_excel(prev, settle)
    else:
        A = settle - prev
    E = {"act360": 360 / f, "act365": 365 / f, "30360us": 360 / f, "actact": nxt - prev}[b]
    DSC = E - A if b == "30360us" else nxt - settle
    cpn = 100 * c["rate"] / f
    R = c["redemption"]
    y = c["yield"]
    N = len(dates)

    def dirty_at(yy):
        if N == 1:
            return (cpn + R) / (1 + DSC / E * yy / f)
        v = 1 + yy / f
        return sum(cpn / v ** (k - 1 + DSC / E) for k in range(1, N + 1)) + R / v ** (N - 1 + DSC / E)

    dirty = dirty_at(y)
    accrued = cpn * A / E
    clean = dirty - accrued
    ys = brentq(lambda yy: dirty_at(yy) - accrued - clean, -0.9 * f, 5, xtol=1e-15, rtol=1e-15, maxiter=500)
    # durations by the same model (Excel DURATION/MDURATION for N > 1)
    v = 1 + y / f
    pv = []
    for k in range(1, N + 1):
        n = k - 1 + DSC / E
        cf = cpn + (R if k == N else 0)
        df = 1 / (1 + DSC / E * y / f) if N == 1 else v ** (-n)
        pv.append((n, cf * df))
    mac = sum(n / f * p for n, p in pv) / dirty
    if N == 1:
        t = mac
        mod = t / (1 + y * t)
        conv = 2 * t * t / (1 + y * t) ** 2
    else:
        mod = mac / v
        conv = sum(p * n * (n + 1) for n, p in pv) / (f * f * v * v) / dirty
    return dict(c, source="Excel transcription", clean=clean, dirty=dirty, accrued=accrued, macaulay=mac,
                modified=mod, convexity=conv, yieldFromClean=ys, prev=iso(prev), next=iso(nxt), N=N, A=A, E=E, DSC=DSC)


