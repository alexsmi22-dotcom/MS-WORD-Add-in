/** Money with grouped thousands and two decimals, true minus ("−1,234.50"). */
export function fmtMoney(v: number): string {
  // Cents half away from zero, as the damages calculators round (toCents: 1.005 is 1.01, not toFixed's 1.00).
  const c = toCents(v);
  const a = Math.abs(c);
  const s = groupThousands(`${Math.floor(a / 100)}.${String(a % 100).padStart(2, "0")}`);
  return c < 0 ? MINUS + s : s;
}

/** Real amounts in base-row dollars and the index rebased to the base row = 100. */
export function constantDollars(nominal: ArrayLike<number>, cpi: ArrayLike<number>, b: number): { real: Float64Array; idx: Float64Array } {
  const n = nominal.length;
  const base = cpi[b];
  const real = new Float64Array(n);
  const idx = new Float64Array(n);
  for (let i = 0; i < n; i++) {
    real[i] = (nominal[i] * base) / cpi[i];
    idx[i] = (cpi[i] / base) * 100;
  }
  return { real, idx };
}

/** idx-deflate: constant dollars. */
export function idxDeflateCalc(read: Read): StatOutput {
  const get = (k: string): string => String(read(k) ?? "");
  const parsed = parseSeriesTable(get("data"), { requireDates: true, minRows: 2 });
  if (!parsed.ok) return refuse(parsed.reason);
  const d = parsed.data;
  const tokens = d.dates!.tokens;
  if (d.cols.length < 2) return refuse("The table needs two value columns: the nominal amount and the price index.");
  const pickOr = (raw: string, j: number): { ok: true; name: string; values: Float64Array } | { ok: false; reason: string } =>
    raw.trim() ? pickSeries(d, raw) : { ok: true, name: d.names[j], values: d.cols[j] };
  const nom = pickOr(get("nominal"), 0);
  if (!nom.ok) return refuse(nom.reason);
  // A blank index field takes the first column that is not the nominal amount.
  const cpi = pickOr(get("index"), d.names[0] === nom.name ? 1 : 0);
  if (!cpi.ok) return refuse(cpi.reason);
  if (nom.name === cpi.name) return refuse(`${q(nom.name)} cannot be both the nominal amount and the price index.`);
  const n = d.n;
  for (let i = 0; i < n; i++) {
    if (!(cpi.values[i] > 0)) return refuse(`${q(cpi.name)} on ${tokens[i].label} is ${fmtFixed(cpi.values[i], 3)}; a price index must be greater than zero.`);
    // Checked on the amount as shown (cents rounded), so 9,999,999,999,999.995 cannot slip through and print as 10¹³.
    if (Math.abs(toCents(nom.values[i])) >= MONEY_MAX * 100) return refuse(`${q(nom.name)} on ${tokens[i].label} is too large to show to the cent (the limit is 10¹³, as the damages calculators).`);
  }
  const findRow = (raw: string, label: string, dflt: number): number | { error: string } => {
    const s = raw.trim();
    if (!s) return dflt;
    // The labels the result table prints ("January 2023", "2019 Q3") name their rows too.
    const byLabel = tokens.findIndex((x) => x.label.toLowerCase() === s.toLowerCase());
    if (byLabel >= 0) return byLabel;
    const t = readDateToken(s, true);
    if (!t || "error" in t || t.len !== s.length) return { error: `${label}: ${q(s)} is not a date or period in the table's form (${tokens[0].label}).` };
    const i = tokens.findIndex((x) => x.from === t.from && x.to === t.to);
    if (i < 0) return { error: `${label}: no row is dated ${t.label}.` };
    return i;
  };
  const b = findRow(get("base"), "Base period", n - 1);
  if (typeof b !== "number") return refuse(b.error);
  const f = findRow(get("from"), "Inflation from", 0);
  if (typeof f !== "number") return refuse(f.error);
  const t = findRow(get("to"), "Inflation to", n - 1);
  if (typeof t !== "number") return refuse(t.error);

  const { real, idx } = constantDollars(nom.values, cpi.values, b);
  for (let i = 0; i < n; i++) {
    if (!Number.isFinite(real[i]) || !Number.isFinite(idx[i]) || Math.abs(real[i]) >= MONEY_MAX) {
      return refuse(`The constant-dollar value on ${tokens[i].label} is not a finite amount that can be shown to the cent (an extreme index ratio).`);
    }
  }
  const infl = (cpi.values[t] / cpi.values[f] - 1) * 100;
  const baseLabel = tokens[b].label;

  const lines: string[] = [];
  lines.push(`Constant dollars: ${q(nom.name)} deflated by ${q(cpi.name)}, in ${baseLabel} dollars (${intText(n)} rows)`);
  lines.push(`Cumulative inflation ${tokens[f].label} to ${tokens[t].label}: ${fmtFixed(infl, 2)}% (index ${fmtFixed(cpi.values[f], 3)} to ${fmtFixed(cpi.values[t], 3)})`);
  lines.push(`${tokens[n - 1].label}: nominal ${fmtMoney(nom.values[n - 1])}, real ${fmtMoney(real[n - 1])}`);
  lines.push("");
  lines.push(
    `Conventions: real = nominal × index(${baseLabel}) / index(t); rebased index = index(t) / index(${baseLabel}) × 100; ` +
      "cumulative inflation = index(to) / index(from) − 1. The index is the one in the table (nothing is bundled); money is shown to the cent with grouped thousands.",
  );
  if (d.dates!.frequency === "irregular") lines.push(`The dates are not evenly spaced${d.dates!.gap ? ` (${d.dates!.gap})` : ""}; each row is deflated on its own index value, so gaps do not change the arithmetic.`);
  lines.push(...d.notes);

  const step = n > DEFLATE_TABLE_MAX_ROWS ? Math.ceil(n / DEFLATE_TABLE_MAX_ROWS) : 1;
  const rows: string[][] = [[d.dates!.name, `${nom.name} (nominal)`, cpi.name, `Index (${baseLabel} = 100)`, `${nom.name} (${baseLabel} dollars)`]];
  for (let i = 0; i < n; i += step) rows.push([tokens[i].label, fmtMoney(nom.values[i]), fmtFixed(cpi.values[i], 3), fmtFixed(idx[i], 3), fmtMoney(real[i])]);
  if (step > 1) {
    if ((n - 1) % step !== 0) rows.push([tokens[n - 1].label, fmtMoney(nom.values[n - 1]), fmtFixed(cpi.values[n - 1], 3), fmtFixed(idx[n - 1], 3), fmtMoney(real[n - 1])]);
    lines.push(`The table shows every ${step}th row and the last (${intText(rows.length - 1)} of ${intText(n)}).`);
  }
  const fstep = n > DEFLATE_FIGURE_MAX_POINTS ? Math.ceil(n / DEFLATE_FIGURE_MAX_POINTS) : 1;
  const nomPts: { x: number; y: number }[] = [];
  const realPts: { x: number; y: number }[] = [];
  for (let i = 0; i < n; i += fstep) {
    const x = decimalYear(tokens[i].from);
    nomPts.push({ x, y: nom.values[i] });
    realPts.push({ x, y: real[i] });
  }
  if (fstep > 1) lines.push(`The figure shows every ${fstep}th row.`);
  const svg = buildPlotSvg(
    [
      { type: "line", points: nomPts, color: "#b45309", label: "Nominal" },
      { type: "line", points: realPts, color: "#0369a1", label: `Real (${baseLabel} dollars)` },
    ],
    { width: 400, height: 260, title: "Nominal and constant dollars", xlabel: "Year", ylabel: nom.name, yGrouping: "comma" },
  );
  return {
    text: lines.join("\n"),
    reading: deflateReading(nom.name, baseLabel, tokens[0].label, tokens[n - 1].label, real[0], real[n - 1], tokens[f].label, tokens[t].label, infl),
    tables: [{ label: `Constant dollars (${baseLabel} = 100)`, rows, align: ["left", "right", "right", "right", "right"] }],
    svg,
  };
}

/**
 * The plain-language reading of a deflation: the amount in constant (base-period) dollars at the first and last rows,
 * as the table prints them (fmtMoney), whether that is a real rise or fall, and the cumulative inflation as printed.
 */
export function deflateReading(
  name: string,
  baseLabel: string,
  firstLabel: string,
  lastLabel: string,
  realFirst: number,
  realLast: number,
  fromLabel: string,
  toLabel: string,
  infl: number,
): string {
  const a = fmtMoney(realFirst);
  const b = fmtMoney(realLast);
  const real = a === b ? "no real change" : realLast > realFirst ? "a real increase" : "a real decrease";
  const inflText = fmtFixed(infl, 2);
  const prices =
    inflText === fmtFixed(0, 2)
      ? `prices were unchanged from ${fromLabel} to ${toLabel}`
      : `prices ${infl > 0 ? "rose" : "fell"} ${fmtFixed(Math.abs(infl), 2)}% from ${fromLabel} to ${toLabel}`;
  return `In ${baseLabel} dollars, ${name} went from ${a} in ${firstLabel} to ${b} in ${lastLabel}, ${real} after inflation; ${prices}.`;
}
