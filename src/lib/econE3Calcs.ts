/** es-event: securities event study with the market model. */
export function esEventCalc(read: Read): StatOutput {
  const get = (k: string): string => {
    const v = read(k);
    return v === undefined || v === null ? "" : String(v);
  };
  const input = (get("input") || "returns") as ReturnInput;
  if (!["returns", "simple", "log"].includes(input)) return refuse(`Unknown input type ${q(get("input"))}.`);
  const unitsRaw = get("units") || "decimal";
  if (unitsRaw !== "decimal" && unitsRaw !== "percent") return refuse(`Unknown return units ${q(unitsRaw)}.`);
  let percentIn = input === "returns" && unitsRaw === "percent";
  const ints: number[] = [];
  const specs: [string, string][] = [
    ["est_from", "Estimation window start"],
    ["est_to", "Estimation window end"],
    ["ev_from", "Event window start"],
    ["ev_to", "Event window end"],
  ];
  for (const [k, label] of specs) {
    const raw = get(k).trim() === "" ? ES_EVENT_DEFAULTS[k] : get(k);
    const v = readIntField(raw, label, -MAX_TAU, MAX_TAU);
    if (typeof v !== "number") return refuse(v.error);
    ints.push(v);
  }
  const [estFrom, estTo, evFrom, evTo] = ints;
  const r = runEventStudy(get("data"), get("events"), { input, market: get("market"), estFrom, estTo, evFrom, evTo });
  if (!r.ok) return refuse(r.reason);
  const res = r.result;
  // "0.12%" cells are percent whatever the units field says (the number reader drops the sign, never the meaning).
  const percentNotes: string[] = [];
  if (res.percentCells && !percentIn) {
    percentIn = true;
    percentNotes.push("The returns carry % signs, so they were read as percent (as if Percent had been chosen).");
  }
  const scale = percentIn ? 1 : 100;
  const N = res.events.length;
  const L1 = res.L1;
  const win = windowText(evFrom, evTo);
  const has11 = res.events[0].car11 !== undefined;
  const pct = (v: number): string => fmtFixed(v * scale, 3);

  const lines: string[] = [];
  lines.push(`Event study, market model: ${N} event${N === 1 ? "" : "s"}, market ${q(res.marketName)}`);
  lines.push(`Estimation window τ = ${tau(estFrom)} to ${tau(estTo)} (L₁ = ${L1} trading days); event window τ = ${tau(evFrom)} to ${tau(evTo)}.`);
  const main = res.tests.filter((t) => t.window === win);
  const j1 = main[0];
  lines.push(`CAAR${win} = ${pct(res.caar[res.caar.length - 1])}%, J₁ = ${fmtFixed(j1.stat!, 3)}, p ${pText(j1.p!)}`);
  lines.push("");
  lines.push(
    "Conventions: market-model OLS on the estimation window, σ²ε with divisor L₁ − 2 (MacKinlay 1997, J. Econ. Lit. 35(1), eqs. 4–6); " +
      "AR = R − α̂ − β̂Rm (eq. 7); event-window AR covariance V = σ²ε(I + X*(X′X)⁻¹X*′), the prediction-error correction " +
      "(Campbell, Lo & MacKinlay 1997, eq. 4.4.9; its diagonal is MacKinlay's eq. 8, printed there without the σ²ε factor on the second term); " +
      "CAR = γ′AR, var(CAR) = γ′Vγ (CLM eqs. 4.4.11–4.4.12).",
  );
  lines.push(
    `Tests: a single event's t is its SCAR = CAR/σ̂(CAR), Student t with L₁ − 2 = ${L1 - 2} df (CLM eq. 4.4.14); ` +
      "J₁ = CAAR/√((1/N²)Σσ̂²ᵢ) and J₂ = √(N(L₁ − 4)/(L₁ − 2))·mean SCAR, both against N(0, 1) (CLM eqs. 4.4.22, 4.4.24); " +
      "BMP = mean SCAR·√N/S with S the cross-sectional SD of the SCARs, divisor N − 1 (Boehmer, Musumeci & Poulsen 1991, " +
      "as given by Kolari & Pynnönen 2009), read here against t(N − 1) as a one-sample t on the SCARs; the cross-sectional test divides the CAAR by √((1/N²)Σ(CARᵢ − CAAR)²), MacKinlay's eq. 21, against N(0, 1). p-values are two-sided.",
  );
  lines.push(
    `An event date that is not a trading day in the table moves to the next trading day. ${percentIn ? "Returns are read as percent." : "Returns, α and σε are shown in percent."}` +
      (input === "simple" ? " Returns are simple returns Pₜ/Pₜ₋₁ − 1 dated by the later day." : input === "log" ? " Returns are log returns ln(Pₜ/Pₜ₋₁) dated by the later day." : ""),
  );
  if (!has11 && !(evFrom === -1 && evTo === 1)) lines.push(`CAR(−1, +1) is not reported: the event window ${win} does not contain days −1 to +1.`);
  lines.push(...percentNotes);
  // Read as decimals, a residual SD above 20% a day is almost always percent numbers ("1.2" meaning 1.2%).
  if (!percentIn && input === "returns" && res.events.some((e) => Math.sqrt(e.fit.sigma2) > 0.2)) {
    lines.push("Check the units: read as decimals, a residual SD above 20% a day suggests the returns are percent numbers; if so, choose Percent.");
  }
  lines.push(...res.notes);

  // Two tables, not one of eleven columns: in Word that width wrapped dates, names and headers inside their cells.
  const mmRows: string[][] = [["Event", "Day used", "α (%)", "β", "σε (%)"]];
  const head = ["Event", `CAR${win} (%)`, "t", "p"];
  if (has11) head.push("CAR(−1, +1) (%)", "t", "p");
  const evRows: string[][] = [head];
  for (const e of res.events) {
    mmRows.push([e.firm, longDay(e.day), pct(e.fit.alpha), fmtFixed(e.fit.beta, 3), pct(Math.sqrt(e.fit.sigma2))]);
    const row = [e.firm, pct(e.car), fmtFixed(e.scar, 3), fmtP(e.p)];
    if (e.car11) row.push(pct(e.car11.car), fmtFixed(e.car11.scar, 3), fmtP(e.car11.p));
    evRows.push(row);
  }
  const dayRows: string[][] = [["τ", "AAR (%)", "CAAR (%)", "SE of CAAR (%)"]];
  for (let k = 0; k < res.taus.length; k++) dayRows.push([tau(res.taus[k]), pct(res.aar[k]), pct(res.caar[k]), pct(res.caarSe[k])]);
  const testRows: string[][] = [["Test", "Window", "Statistic", "Reference", "p"]];
  for (const t of res.tests) testRows.push([t.name, t.window, t.stat === undefined ? t.why ?? "" : fmtFixed(t.stat, 3), t.reference, t.p === undefined ? "" : fmtP(t.p)]);
  const tables: StatTable[] = [
    { label: "Events: market model on the estimation window", rows: mmRows, align: ["left", "left", "right", "right", "right"] },
    { label: "Events: cumulative abnormal returns", rows: evRows, align: ["left", ...head.slice(1).map((): "right" => "right")], note: `t = SCAR = CAR/σ̂(CAR), Student t with ${L1 - 2} df.` },
    { label: `Average abnormal returns by event day (N = ${N})`, rows: dayRows, align: ["right", "right", "right", "right"], note: "SE of CAAR = √((1/N²)Σ var(CARᵢ(τ₁, τ))) with the prediction-error covariance." },
    { label: "Aggregate tests", rows: testRows, align: ["left", "left", "right", "left", "right"] },
  ];

  const mid = res.taus.map((t, k) => ({ x: t, y: res.caar[k] * scale }));
  const up = res.taus.map((t, k) => ({ x: t, y: (res.caar[k] + 1.96 * res.caarSe[k]) * scale }));
  const dn = res.taus.map((t, k) => ({ x: t, y: (res.caar[k] - 1.96 * res.caarSe[k]) * scale }));
  const svg = buildPlotSvg(
    [
      { type: "line", points: mid, color: "#0369a1", label: "CAAR" },
      { type: "line", points: up, color: "#94a3b8", label: "±1.96 SE" },
      { type: "line", points: dn, color: "#94a3b8" },
      { type: "line", points: [{ x: res.taus[0], y: 0 }, { x: res.taus[res.taus.length - 1], y: 0 }], color: "#cbd5e1" },
    ],
    { width: 400, height: 260, title: "Average cumulative abnormal return", xlabel: "Event day τ", ylabel: "CAAR (%)" },
  );
  const caarEnd = res.caar[res.caar.length - 1];
  return { text: lines.join("\n"), reading: eventStudyReading(N, win, caarEnd, j1.stat!, j1.p!, pct), tables, svg };
}

/**
 * The plain-language reading of an event study: the average cumulative abnormal return over the event window (the
 * move beyond what the market model predicts), as the summary line prints it, and whether J₁ finds it unlikely to be
 * chance at p < 0.05.
 */
export function eventStudyReading(n: number, win: string, caar: number, j1: number, p: number, pct: (v: number) => string): string {
  const who = n === 1 ? "The stock" : `Across the ${n} events, the average stock`;
  const dir = pct(caar) === pct(0) ? "moved" : caar > 0 ? "rose" : "fell";
  const head = `${who} ${dir} by about ${pct(Math.abs(caar))}% beyond what the market explains over event days ${win}`;
  const stat = `J₁ = ${fmtFixed(j1, 3)}, p ${pText(p)}`;
  // Decided on the p as printed (calcReading's pVerdict): exactly 0.050 as printed is borderline.
  const v = pVerdict(`p ${pText(p)}`);
  if (v === "borderline") return `${head} (${stat}), ${BOUNDARY_CLAUSE}.`;
  return v === "clear"
    ? `${head}, an abnormal reaction unlikely to be chance alone (${stat}).`
    : `${head}; the data show no clear abnormal reaction (${stat}), so a move this size could be chance.`;
}

function pText(p: number): string {
  return p < 0.001 ? fmtP(p) : `= ${fmtP(p)}`;
}

function longDay(day: number): string {
  const { y, m, d } = civilFromDay(day);
  return `${y}-${String(m).padStart(2, "0")}-${String(d).padStart(2, "0")}`;
}

